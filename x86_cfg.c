/*
 * x86_cfg.c -- the per-game .cfg parser, in DOSBox's own configuration syntax.
 * See x86_cfg.h for the contract and x86_settings.h for the three layers.
 *
 * Freestanding C89-ish, no allocation, no I/O, no strtol, no locale. Compiles
 * for the host harness and for cortex-m7 from this one source.
 *
 * COLD PATH ONLY. Once at launch, before the CPU is initialised.
 */

#include <stdio.h>
#include <string.h>
#include "x86_settings.h"
#include "x86_cfg.h"

/* NEGATIVE CONTROLS -- 0 in every real build. See the block of the same name in
   x86_settings.c for why they exist and what runs them. */
#ifndef X86_CFG_CTL_NOBINARY
#define X86_CFG_CTL_NOBINARY 0    /* 1: do not sniff for a non-text file    */
#endif
#ifndef X86_CFG_CTL_NOTOOBIG
#define X86_CFG_CTL_NOTOOBIG 0    /* 1: parse a file past X86_CFG_MAX_BYTES */
#endif

/* ---- Value kinds --------------------------------------------------------- */
typedef enum {
    X86_CFG_T_BOOL = 0,   /* DOSBox spelling: true/false. on/off/yes/no/1/0
                             are taken too -- see cfg_val_bool()             */
    X86_CFG_T_INT,        /* a plain decimal integer. RANGE IS NOT CHECKED
                             HERE: x86_settings_base_set() rejects
                             out-of-range against x86_setting_desc[], which is
                             the one table that owns each setting's bounds. A
                             second copy of a bound is a second thing to keep
                             in step.                                        */
    X86_CFG_T_MEMKB,      /* an integer in KB with a granularity rule        */
    X86_CFG_T_ONOFFKB,    /* DOSBox's `xms = true` / `ems = false`: a bool
                             that lands in a KB setting                      */
    X86_CFG_T_CYCLES,     /* DOSBox's `cycles`: `max`/`auto`, or a number    */
    X86_CFG_T_STR         /* free text, stored in x86_settings.c's fixed
                             storage. `.cfg`-only -- see x86_settings.h      */
} x86_cfg_type_t;

/*
 * ---- The key table ---------------------------------------------------------
 *
 * DOSBOX'S SYNTAX AND, WHERE ONE EXISTS, DOSBOX'S SPELLING. The owner asked for
 * a file a human edits by hand and for it to look like a dosbox.conf, and the
 * payoff is not cosmetic: `[cpu] cycles`, `[dos] xms`/`ems` and `[autoexec]`
 * are things people already know, already have in their own configs, and can
 * copy across. Where this core has a knob DOSBox does not, the key is new and
 * sits in the section it belongs to.
 *
 * SECTIONS ARE RECOGNISED BUT NOT REQUIRED, deliberately. DOSBox refuses a key
 * outside its section; that is right for a program with two hundred keys and
 * wrong for one with nine, and being strict would break every `.cfg` already on
 * the card -- which is FLAT, with no section headers at all (they are the prior
 * port's files; see below). So a key is matched on its name and its section is
 * checked only when both the file and the table name one. An unknown section is
 * not an error and its keys are still looked up.
 *
 * EVERY KEY HERE IS WIRED TO SOMETHING A GUEST OR A USER CAN OBSERVE. That is
 * the entry requirement, not a nice-to-have: a documented key that nothing
 * reads is a subsystem that passes its tests while no guest can reach it, with
 * better packaging.
 *
 * ---- WHAT THE PRIOR PORT'S KEYS DO HERE, AND WHY THAT IS NOT A BUG ---------
 *
 * Every .cfg on the card today was generated by the PRIOR port and names its
 * keys: ss_big_stack, fast_boot, dos_high, boot_keys, files, buffers. NONE of
 * those exist in this core -- it has a real descriptor-cached SS.B rather than
 * a compile-time stack-width switch, no fast-boot snapshot, and it HLEs DOS
 * rather than booting one that reads a CONFIG.SYS. So they land on the UNKNOWN
 * path: counted, the first one named, and ignored.
 *
 * That is exactly the behaviour the format was built for and it is why the
 * shipped files are safe to leave in place: as generated EVERY LINE IN THEM IS
 * COMMENTED OUT, so today they parse to "applied 0" and change nothing at all.
 * A user who uncomments one gets one line saying it was not understood, rather
 * than a silent no-op or a refused launch.
 */
typedef struct {
    const char      *name;
    const char      *section;  /* NULL = accepted in any section */
    int              id;       /* x86_setting_id_t, or x86_setting_str_id_t
                                  when the type is _T_STR */
    x86_cfg_type_t   type;
} x86_cfg_key_t;

static const x86_cfg_key_t x86_cfg_keys[] = {
    /* ---- [cpu] -------------------------------------------------------------
     *
     * DOSBox's own key, its own units, and its own `max`. `cycles` is guest
     * instructions per MILLISECOND there and `guest_kips` is thousands per
     * SECOND here, which is the same number -- so a figure copied out of a
     * dosbox.conf means what its author meant it to mean.
     *
     * `cycles` resolves to the nearest rung of src/main.c's profile table,
     * which is done by the CONSUMER because the consumer owns that table.
     * `cpu_profile` is the escape hatch for naming a rung outright, and is what
     * the PAUSE/SET row and the .dosset use. */
    { "cycles",       "cpu",  X86_SET_CPU_CYCLES,  X86_CFG_T_CYCLES },
    { "cpu_profile",  "cpu",  X86_SET_CPU_PROFILE, X86_CFG_T_INT    },

    /* ---- [dos] -------------------------------------------------------------
     *
     * `xms` and `ems` are DOSBox's booleans and mean the same thing here:
     * false turns the interface off for this title. The `_kb` spellings are
     * this core's addition, because "how much" is a real question here in a way
     * it is not on a PC with a gigabyte of RAM -- EMS pages come out of the
     * pager's aux window and XMS out of the pagefile.
     *
     * They are the SAME setting id, so writing both is last-one-wins within the
     * file rather than a conflict with no defined answer. */
    { "xms",          "dos",  X86_SET_XMS_KB,      X86_CFG_T_ONOFFKB },
    { "ems",          "dos",  X86_SET_EMS_KB,      X86_CFG_T_ONOFFKB },
    { "xms_kb",       "dos",  X86_SET_XMS_KB,      X86_CFG_T_MEMKB   },
    { "ems_kb",       "dos",  X86_SET_EMS_KB,      X86_CFG_T_MEMKB   },

    /* ---- launch parameters, written out ------------------------------------
     *
     * The `[autoexec]` section below is the DOSBox way and is what most files
     * will use. These three are the same three values named directly, for a
     * file that would rather be explicit than write a command line -- and they
     * are what `[autoexec]` itself writes into, so there is one representation
     * and not two.
     *
     * `use_cmdtail` is this core's existing `guest_use_cmdtail` knob, which
     * until now was reachable only by writing it over the debug backend: it
     * decides whether the guest's OWN AUTOEXEC.BAT command tail is passed on
     * when this file does not name one. */
    { "entry",        NULL,   X86_STR_ENTRY,       X86_CFG_T_STR  },
    { "args",         NULL,   X86_STR_ARGS,        X86_CFG_T_STR  },
    { "cwd",          NULL,   X86_STR_CWD,         X86_CFG_T_STR  },
    { "use_cmdtail",  NULL,   X86_SET_USE_CMDTAIL, X86_CFG_T_BOOL },
};
#define X86_CFG_KEY_COUNT ((int)(sizeof x86_cfg_keys / sizeof x86_cfg_keys[0]))

/* The granularity each KB key is quantised to. XMS is a block-copy interface
   served out of a byte range of the pagefile, so any KB is expressible and 1 is
   honest. EMS hands out 16 KB LOGICAL PAGES and a page is all-or-nothing: 8 and
   24 must be REFUSED rather than rounded, because a reservation that cannot
   hold a whole page is the silent-discard failure the EMS layer is written
   around. */
static unsigned x86_cfg_gran_kb(int id)
{
    return id == X86_SET_EMS_KB ? 16u : 1u;
}

/* What `xms = true` / `ems = true` mean in KB. `true` is "the amount you would
   have given me anyway", which is the only reading that makes DOSBox's boolean
   mean what its author expects on a machine where the amount is a choice. */
static int x86_cfg_on_kb(int id)
{
    return id == X86_SET_EMS_KB ? 1024 : 4096;
}

const char *x86_cfg_key_name(int i)
{
    if (i < 0 || i >= X86_CFG_KEY_COUNT)
        return 0;
    return x86_cfg_keys[i].name;
}

const char *x86_cfg_key_section(int i)
{
    if (i < 0 || i >= X86_CFG_KEY_COUNT)
        return 0;
    return x86_cfg_keys[i].section;
}

int x86_cfg_key_id(int i)
{
    if (i < 0 || i >= X86_CFG_KEY_COUNT)
        return -1;
    return x86_cfg_keys[i].id;
}

int x86_cfg_key_is_str(int i)
{
    if (i < 0 || i >= X86_CFG_KEY_COUNT)
        return 0;
    return x86_cfg_keys[i].type == X86_CFG_T_STR;
}

const char *x86_cfg_status_name(x86_cfg_status_t s)
{
    switch (s) {
    case X86_CFG_OK:      return "OK";
    case X86_CFG_EABSENT: return "ABSENT";
    case X86_CFG_ETOOBIG: return "TOOBIG";
    case X86_CFG_EBINARY: return "BINARY";
    }
    return "?";
}

/*
 * ---- Character classification, done here rather than via ctype.h -----------
 *
 * ctype.h is locale-dependent and its arguments are int-with-a-trap (a plain
 * char with the top bit set is undefined behaviour through isspace()). A .cfg
 * on an SD card can contain any byte at all, so the classification is spelled
 * out. It is also four instructions.
 */
static int cfg_is_space(unsigned char c)
{
    return c == ' ' || c == '\t' || c == '\r' || c == '\f' || c == '\v';
}

static unsigned char cfg_lower(unsigned char c)
{
    return (c >= 'A' && c <= 'Z') ? (unsigned char)(c - 'A' + 'a') : c;
}

/* Case-insensitive compare of [a, a_end) against the NUL-terminated `b`.
   KEYS, SECTIONS AND BOOLEAN VALUES ARE ALL CASE-INSENSITIVE, as they are in
   DOSBox: a file a human types is going to contain `[CPU]` and `Cycles = Max`,
   and refusing it -- or worse, silently ignoring it, which is what a
   case-sensitive lookup does -- is a support question nobody should have to
   ask. String VALUES are of course kept verbatim. */
static int cfg_eq(const unsigned char *a, const unsigned char *a_end, const char *b)
{
    while (a < a_end && *b) {
        if (cfg_lower(*a) != cfg_lower((unsigned char)*b))
            return 0;
        a++; b++;
    }
    return a == a_end && *b == 0;
}

/* Does [a, a_end) begin with `b` (case-insensitively) and then end or continue
   with whitespace? For the `[autoexec]` verbs, where `cd` must match `cd games`
   but not `cdplayer`. */
static const unsigned char *cfg_verb(const unsigned char *a,
                                     const unsigned char *a_end, const char *b)
{
    while (a < a_end && *b) {
        if (cfg_lower(*a) != cfg_lower((unsigned char)*b))
            return 0;
        a++; b++;
    }
    if (*b)
        return 0;
    if (a == a_end)
        return a;
    if (!cfg_is_space(*a) && *a != '\\' && *a != '/')
        return 0;
    return a;
}

static void cfg_keep(char *dst, const unsigned char *a, const unsigned char *a_end)
{
    unsigned long n = (unsigned long)(a_end - a);

    if (n > X86_CFG_NAME_MAX - 1)
        n = X86_CFG_NAME_MAX - 1;
    if (n)
        memcpy(dst, a, (size_t)n);
    dst[n] = 0;
}

/*
 * ---- Value parsers ---------------------------------------------------------
 *
 * Each returns 1 and writes *out, or 0 for "this is not a value of that kind".
 * NOTHING IS CLAMPED. A clamp invents a number nobody chose and then behaves as
 * if they had; the range is documented and a value outside it is reported by
 * name while the setting keeps its default.
 */

/* DOSBox writes true/false. Everything else here is the prior port's list, kept
   because somebody hand-editing a DOS config writes `on` about as often. */
static int cfg_val_bool(const unsigned char *v, const unsigned char *v_end, int *out)
{
    static const char *const yes[] = { "true", "on", "yes", "1", "enabled", "enable" };
    static const char *const no[]  = { "false", "off", "no", "0", "disabled", "disable" };
    int i;

    for (i = 0; i < (int)(sizeof yes / sizeof yes[0]); i++)
        if (cfg_eq(v, v_end, yes[i])) { *out = 1; return 1; }
    for (i = 0; i < (int)(sizeof no / sizeof no[0]); i++)
        if (cfg_eq(v, v_end, no[i])) { *out = 0; return 1; }
    return 0;
}

/* A non-negative decimal integer, with overflow refused rather than wrapped. */
static int cfg_val_uint(const unsigned char *v, const unsigned char *v_end, int *out)
{
    long acc = 0;

    if (v == v_end)
        return 0;
    while (v < v_end) {
        if (*v < '0' || *v > '9')
            return 0;
        acc = acc * 10 + (*v - '0');
        if (acc > 1000000L)      /* far past any range in the table; refuse */
            return 0;
        v++;
    }
    *out = (int)acc;
    return 1;
}

/* A memory size in KB. THE GRANULARITY RULE IS ENFORCED HERE AND NOT BY THE
   RANGE, because 0 has to stay legal -- it is "advertise none" -- while a
   non-multiple must not be. */
static int cfg_val_memkb(const unsigned char *v, const unsigned char *v_end,
                         unsigned gran, int *out)
{
    int n;

    if (!cfg_val_uint(v, v_end, &n))
        return 0;
    if (n == 0) { *out = 0; return 1; }
    if (gran > 1u && ((unsigned)n % gran) != 0u)
        return 0;
    *out = n;
    return 1;
}

/* ---- The parse ----------------------------------------------------------- */

/*
 * `[autoexec]`, and what this core can honestly do with it.
 *
 * DOSBox runs those lines as a batch file. This core does not have a shell to
 * run them in -- it HLEs DOS and launches exactly one program -- so what it
 * takes from the section is the two things a launch actually needs: WHERE to
 * run and WHAT to run. A line is therefore one of three things:
 *
 *   `cd <path>`      the working directory. Also `cd\path`, which is what a
 *                    real AUTOEXEC.BAT is full of.
 *   an inert verb    `mount`, `imgmount`, `echo`, `@echo`, `cls`, `pause`,
 *                    `exit`, `set`, `keyb`, `loadhigh`/`lh`, or a bare drive
 *                    letter like `c:`. IGNORED, and deliberately not counted as
 *                    an error: a config copied wholesale from a desktop DOSBox
 *                    will be full of them and none of them is a mistake, it is
 *                    just work this core does elsewhere.
 *   anything else    the program to run, and the rest of the line is its
 *                    arguments. LAST ONE WINS, which is what a batch file's own
 *                    semantics amount to when only one program can start.
 *
 * The honest limit, stated rather than hidden: a line this core ignores is
 * ignored SILENTLY. `x86_cfg_report()` says how many commands the section
 * yielded, so a user whose `mount` line was skipped can see that the entry they
 * expected is not the entry that was taken.
 */
static int cfg_autoexec_inert(const unsigned char *s, const unsigned char *e)
{
    static const char *const verbs[] = {
        "mount", "imgmount", "echo", "@echo", "cls", "pause", "exit",
        "set", "keyb", "loadhigh", "lh", "rem", "call", "config", "ver",
    };
    int i;

    /* A bare drive letter: `c:` or `C:\`. */
    if (e - s >= 2 && ((s[0] >= 'a' && s[0] <= 'z') || (s[0] >= 'A' && s[0] <= 'Z'))
        && s[1] == ':') {
        const unsigned char *p = s + 2;
        while (p < e && (*p == '\\' || *p == '/'))
            p++;
        if (p == e)
            return 1;
    }
    for (i = 0; i < (int)(sizeof verbs / sizeof verbs[0]); i++)
        if (cfg_verb(s, e, verbs[i]))
            return 1;
    return 0;
}

/* Split [s, e) into a first word and a tail, and store them as entry and args.
   Returns 1 if it took. */
static int cfg_autoexec_command(const unsigned char *s, const unsigned char *e)
{
    const unsigned char *w = s;
    const unsigned char *tail;
    int ok;

    while (w < e && !cfg_is_space(*w))
        w++;
    ok = x86_settings_str_set(X86_STR_ENTRY, (const char *)s,
                              (unsigned long)(w - s));
    if (!ok)
        return 0;

    tail = w;
    while (tail < e && cfg_is_space(*tail))
        tail++;
    /* ALWAYS set args, even to empty. A command line in `[autoexec]` is a
       complete statement of how to launch: "with no arguments" is something it
       said, not something it left open, and letting the guest's own
       AUTOEXEC.BAT tail leak in behind it would be a launch nobody wrote. */
    return x86_settings_str_set(X86_STR_ARGS, (const char *)tail,
                                (unsigned long)(e - tail));
}

x86_cfg_status_t x86_cfg_parse(const unsigned char *buf, unsigned long len,
                               x86_cfg_result_t *out)
{
    x86_cfg_result_t r;
    unsigned long i;
    /* The section in force. Bounded and NUL-terminated; a longer header is kept
       truncated, which only ever affects a section this table does not name. */
    char section[X86_CFG_NAME_MAX];
    int in_autoexec = 0;

    memset(&r, 0, sizeof r);
    section[0] = 0;

    /* FIRST, unconditionally, before anything below can go wrong: the previous
       title's .cfg is gone. x86_cfg.h states why there is no path around this. */
    x86_settings_base_clear();

    if (!buf || len == 0)
        { if (out) *out = r; return X86_CFG_EABSENT; }
#if !X86_CFG_CTL_NOTOOBIG
    if (len > X86_CFG_MAX_BYTES)
        { if (out) *out = r; return X86_CFG_ETOOBIG; }
#endif

    /* IS IT TEXT AT ALL? A .cfg that is actually a renamed .dsk, a savestate or
       a half-written file would otherwise be scanned line by line, produce a
       pile of `malformed` and a diagnostic about configuration syntax, and send
       somebody looking for a typo in a binary. One NUL or one control byte
       settles it, and the whole file is refused rather than half-applied. */
#if !X86_CFG_CTL_NOBINARY
    for (i = 0; i < len; i++) {
        unsigned char c = buf[i];
        if (c == 0 || (c < 0x20 && c != '\n' && c != '\r' && c != '\t'))
            { if (out) *out = r; return X86_CFG_EBINARY; }
    }
#endif

    i = 0;
    while (i < len) {
        const unsigned char *k, *k_end, *v, *v_end, *eq;
        unsigned long ls = i, le;
        int j, val;

        while (i < len && buf[i] != '\n')
            i++;
        le = i;
        if (i < len)
            i++;                    /* step over the '\n' */

        /* Trim. \r is whitespace here, so CRLF files -- which is what anybody
           editing on Windows will produce -- parse identically to LF ones. */
        while (ls < le && cfg_is_space(buf[ls]))
            ls++;
        while (le > ls && cfg_is_space(buf[le - 1]))
            le--;
        if (ls == le)
            continue;               /* blank */
        if (buf[ls] == '#' || buf[ls] == ';')
            continue;               /* comment. DOSBox writes '#'; DOS users
                                       write ';'. Both, so neither surprises. */

        /* ---- a section header ------------------------------------------- */
        if (buf[ls] == '[') {
            unsigned long p = ls + 1, q;
            for (q = p; q < le && buf[q] != ']'; q++)
                ;
            if (q < le) {
                unsigned long n = q - p;
                if (n > X86_CFG_NAME_MAX - 1)
                    n = X86_CFG_NAME_MAX - 1;
                {
                    unsigned long t;
                    for (t = 0; t < n; t++)
                        section[t] = (char)cfg_lower(buf[p + t]);
                    section[n] = 0;
                }
                in_autoexec = (strcmp(section, "autoexec") == 0);
                continue;
            }
            /* A '[' with no ']' is not a header and not a key. */
            r.malformed++;
            continue;
        }

        /* ---- inside [autoexec]: command lines, not key=value ------------- */
        if (in_autoexec) {
            /* Note the ORDER: no trailing-comment strip and no '=' hunt in
               here. A DOS command line may legitimately contain both, and
               cutting one in half to honour a syntax that does not apply in
               this section would be a data-loss bug rather than a parse. */
            if (cfg_autoexec_inert(buf + ls, buf + le))
                continue;
            {
                /* `cd GAMES`, `cd\GAMES`, `chdir GAMES`. A real AUTOEXEC.BAT is
                   full of these and they are the other half of "where to run". */
                const unsigned char *p = cfg_verb(buf + ls, buf + le, "cd");
                if (!p)
                    p = cfg_verb(buf + ls, buf + le, "chdir");
                if (p) {
                    while (p < buf + le && cfg_is_space(*p))
                        p++;
                    if (!x86_settings_str_set(X86_STR_CWD, (const char *)p,
                                              (unsigned long)(buf + le - p))) {
                        if (r.bad_value == 0)
                            cfg_keep(r.first_bad, buf + ls, buf + le);
                        r.bad_value++;
                    } else {
                        r.applied++;
                    }
                    continue;
                }
            }
            if (cfg_autoexec_command(buf + ls, buf + le)) {
                r.applied++;
                r.commands++;
            } else {
                if (r.bad_value == 0)
                    cfg_keep(r.first_bad, buf + ls, buf + le);
                r.bad_value++;
            }
            continue;
        }

        /* A trailing comment. Deliberately requires WHITESPACE before the
           marker, so a value that legitimately contains one is not cut in half
           by it -- which matters now that `args` exists and a command tail may
           contain anything at all. */
        {
            unsigned long p;
            for (p = ls; p + 1 < le; p++)
                if (cfg_is_space(buf[p])
                    && (buf[p + 1] == '#' || buf[p + 1] == ';')) {
                    le = p;
                    break;
                }
            while (le > ls && cfg_is_space(buf[le - 1]))
                le--;
            if (ls == le)
                continue;
        }

        eq = 0;
        {
            unsigned long p;
            for (p = ls; p < le; p++)
                if (buf[p] == '=' || buf[p] == ':') { eq = buf + p; break; }
        }
        if (!eq) {
            /* A line with content and no separator. Counted, not fatal, and not
               logged on its own line. */
            r.malformed++;
            continue;
        }

        k = buf + ls; k_end = eq;
        v = eq + 1;   v_end = buf + le;
        while (k_end > k && cfg_is_space(k_end[-1]))
            k_end--;
        while (v < v_end && cfg_is_space(*v))
            v++;
        /* A value may be quoted; strip one matching pair. Costs four lines and
           removes a whole class of "why did `args = "-l"` not work" -- and for
           `args` it is the only way to write a value with leading or trailing
           spaces that survives the trim above. */
        if (v_end - v >= 2 && (*v == '"' || *v == '\'') && v_end[-1] == *v) {
            v++; v_end--;
        }

        if (k == k_end) { r.malformed++; continue; }

        for (j = 0; j < X86_CFG_KEY_COUNT; j++) {
            if (!cfg_eq(k, k_end, x86_cfg_keys[j].name))
                continue;
            /* The section is checked only when BOTH the file and the table name
               one -- see the table's header on why this is lenient. */
            if (x86_cfg_keys[j].section && section[0]
                && strcmp(section, x86_cfg_keys[j].section) != 0)
                continue;
            break;
        }
        if (j == X86_CFG_KEY_COUNT) {
            /* UNKNOWN IS NOT FATAL. An old firmware must run a newer .cfg -- and
               here, a file copied out of a desktop dosbox.conf will name dozens
               of keys this core has never had. Counted, and the first one
               named, so it is not SILENT either. */
            if (r.unknown == 0)
                cfg_keep(r.first_unknown, k, k_end);
            r.unknown++;
            continue;
        }

        if (x86_cfg_keys[j].type == X86_CFG_T_STR) {
            /* An EMPTY value is legal and meaningful: `args =` says "run it
               with no arguments", which is not the same as saying nothing and
               letting the guest's own AUTOEXEC.BAT decide.
               x86_settings_str_is_set() distinguishes them; the length check
               inside str_set() is what refuses one too long. */
            if (!x86_settings_str_set((x86_setting_str_id_t)x86_cfg_keys[j].id,
                                      (const char *)v,
                                      (unsigned long)(v_end - v))) {
                if (r.bad_value == 0)
                    cfg_keep(r.first_bad, k, k_end);
                r.bad_value++;
                continue;
            }
            r.applied++;
            continue;
        }

        val = 0;
        {
            int parsed;
            int id = x86_cfg_keys[j].id;

            switch (x86_cfg_keys[j].type) {
            case X86_CFG_T_BOOL:
                parsed = cfg_val_bool(v, v_end, &val);
                break;
            case X86_CFG_T_ONOFFKB:
                parsed = cfg_val_bool(v, v_end, &val);
                if (parsed)
                    val = val ? x86_cfg_on_kb(id) : 0;
                break;
            case X86_CFG_T_MEMKB:
                parsed = cfg_val_memkb(v, v_end, x86_cfg_gran_kb(id), &val);
                break;
            case X86_CFG_T_CYCLES:
                /* `max` and `auto` are DOSBox's own words for "as fast as it
                   goes", and that is a RUNG of the profile table (index 0,
                   "Max") rather than a cycle count -- so it is written to the
                   profile and not to cycles. Anything else is a number in kips
                   and the consumer picks the nearest rung. */
                if (cfg_eq(v, v_end, "max") || cfg_eq(v, v_end, "auto")) {
                    id = X86_SET_CPU_PROFILE;
                    val = 0;
                    parsed = 1;
                } else {
                    parsed = cfg_val_uint(v, v_end, &val);
                }
                break;
            default:
                parsed = cfg_val_uint(v, v_end, &val);
                break;
            }
            if (!parsed || !x86_settings_base_set((x86_setting_id_t)id, val)) {
            /* The key was understood and the value was not -- or was, and fell
               outside the range x86_settings.c will accept. Either way this
               setting keeps its firmware default and the REST OF THE FILE IS
               STILL HONOURED: one bad line is not evidence against the others,
               and throwing the lot away turns a typo into a total loss. */
                if (r.bad_value == 0)
                    cfg_keep(r.first_bad, k, k_end);
                r.bad_value++;
                continue;
            }
        }
        r.applied++;
    }

    if (out)
        *out = r;
    return X86_CFG_OK;
}

/* ---- The one line -------------------------------------------------------- */

void x86_cfg_report(const char *label, x86_cfg_status_t st,
                    const x86_cfg_result_t *r)
{
    if (!label)
        label = "cfg";

    /* NO FILE IS NOT AN EVENT. A line per launch saying "everything is normal"
       is how a small wrapping log ring loses the line that mattered. */
    if (st == X86_CFG_EABSENT)
        return;

    if (st != X86_CFG_OK) {
        printf("DOS: %s %s -- ignored, running on defaults\n",
               label, x86_cfg_status_name(st));
        return;
    }
    if (!r)
        return;

    /* Everything understood and nothing to warn about: still ONE line, because
       a config that quietly changes how the machine behaves is the thing that
       turns a bug report into an afternoon. Nothing applied and nothing wrong
       means a file of comments -- which is every .cfg on the card today -- and
       that is worth one line too: a user who wrote a .cfg and sees no effect
       needs to know it was read.

       The `[autoexec]` count is separate because that section's inert lines are
       skipped in silence: seeing "0 command(s)" from a section a user filled in
       is what tells them their launch line was one of the ones this core does
       not run. */
    /* ONE format, not two, and terse. The counts say how much went wrong and
       the two names say where to start looking; anything longer is .rodata,
       and .rodata here comes out of RAM_EMU -- the same pool the guest's pages
       are cut from, where 1,272 bytes is a whole 4 KB page of guest memory.
       An `unknown` count is NOT an error and the wording must not imply one:
       every .cfg on the card names keys from the prior port. */
    printf("DOS: %s applied %u, cmd %u, unknown %u %s, bad %u %s, malformed %u\n",
           label, (unsigned)r->applied, (unsigned)r->commands,
           (unsigned)r->unknown, r->unknown ? r->first_unknown : "",
           (unsigned)r->bad_value, r->bad_value ? r->first_bad : "",
           (unsigned)r->malformed);
}
