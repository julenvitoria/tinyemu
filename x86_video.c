#endif

#define AA_NONE 0xFFu

static uint32_t *cga_clut;      /* the LUT8 CLUT the LCD scans out through */
/* Set whenever the four active colours change. The frame loop re-pushes the
   CLUT on it: the firmware copies our table into its own, so editing ours
   after the fact would never reach the panel. */
uint32_t cga_clut_dirty;

/*
 * Recompute the four active colours from the mode/colour-select registers.
 *
 * Mode 4 takes colour 0 from the background field of 0x3D9 -- it is a real
 * register, not a constant, and games change it -- while colours 1..3 come
 * from the palette pair selected by bit 5, brightened by bit 4. The
 * black-and-white bit in 0x3D8 selects a third set on real hardware.
 */
void x86_video_refresh_palette(void)
{
    if (!cga_clut)
        return;
    /* EGA 0Dh owns the whole 32-entry table -- sixteen colours through the
       Attribute Controller and their mirrors -- and ega_sync_palette() is the
       only writer while it is up. Falling through here would paint the CGA
       four-colour block over it, and because that path leaves ega_clut_valid
       set the EGA palette would never be recomputed to correct it. */
    if (cur_desc->kind == VM_EGA4) {
        ega_clut_valid = 0;             /* recompute at the next blit */
        return;
    }
    ega_clut_valid = 0;                 /* any other mode invalidates it too */

    unsigned sel = x86_io.cga_color_select;
    unsigned background = sel & 0x0F;
    unsigned bright = (sel & 0x10) ? 8u : 0u;

    /* Which four colours the graphics block holds.
     *
     * Keyed on the MODE NUMBER, not on the 0x3D8 black-and-white bit, which is
     * the previous port's rule: mode 5 IS the colour-burst-off palette whether
     * or not anyone wrote the register, and a guest that sets its mode through
     * INT 10h may never write 0x3D8 at all. The register is still honoured
     * (bit 2) for a guest that does drive it directly. */
    unsigned c0 = background, c1, c2, c3;
    if (cur_desc->kind == VM_CGA1) {
        /* 640x200 is two colours. Pixel 0 is black and pixel 1 takes the
           foreground from the low nibble -- and an UNTOUCHED 0x3D9 (zero) has
           to mean white on black, or the whole screen is black on black. */
        c0 = 0;
        c1 = c2 = c3 = background ? background : 15;
    } else if (video_mode == 0x05 || (x86_io.cga_mode & 0x04)) {
        c1 = 3 | bright; c2 = 4 | bright; c3 = 7 | bright;   /* cyan/red/white */
    } else if (sel & 0x20) {
        c1 = 3 | bright; c2 = 5 | bright; c3 = 7 | bright;   /* cyan/magenta/grey */
    } else {
        c1 = 2 | bright; c2 = 4 | bright; c3 = 6 | bright;   /* green/red/brown */
    }

    /*
     * ONE CLUT LAYOUT FOR EVERY MODE, which is the previous port's arrangement
     * and worth the change on its own: 0-15 are the fixed CGA palette that text
     * attributes index directly, 16-19 are the four currently selected graphics
     * colours, and 20-31 mirror 4-15 so no index anywhere lands on an
     * uninitialised entry.
     *
     * The old layout put the graphics colours in 0-3, which meant a mode switch
     * had to REWRITE the whole table in both directions and entry 0 -- the
     * letterbox clear, and the colour any stray byte draws in -- was the
     * guest's chosen background rather than black. Here a mode change moves
     * four entries and nothing else can be left stale by it.
     */
    for (unsigned i = 0; i < X86_TEXT_CLUT_ENTRIES; i++)
        cga_clut[i] = cga_argb[i & 15];
    cga_clut[X86_GFX_CLUT_BASE + 0] = cga_argb[c0 & 15];
    cga_clut[X86_GFX_CLUT_BASE + 1] = cga_argb[c1 & 15];
    cga_clut[X86_GFX_CLUT_BASE + 2] = cga_argb[c2 & 15];
    cga_clut[X86_GFX_CLUT_BASE + 3] = cga_argb[c3 & 15];
#if X86_TEXT_AA
    if (cur_desc->kind == VM_TEXT)
        aa_nblocks = 0;                 /* force a rebuild if AA is on */
#endif
    cga_clut_dirty = 1;
}

void x86_video_init(void *vram, void *lut8_palette)
{
    cga_vram = (uint8_t *)vram;
    cga_clut = (uint32_t *)lut8_palette;
    memset(cga_vram, 0, X86_VRAM_BYTES);

    /* CGA packs the leftmost pixel in the HIGH bits of each byte. The table is
       built so a little-endian word store lands them left to right, and every
       entry carries the graphics block base so the blitter's output indexes the
       CLUT directly. */
    for (unsigned b = 0; b < 256; b++) {
        cga_expand[b] = (X86_GFX_CLUT_BASE * 0x01010101u)
                      + (((b >> 6) & 3)
                      | (((b >> 4) & 3) << 8)
                      | (((b >> 2) & 3) << 16)
                      | (((b >> 0) & 3) << 24));
    }

    /* Mode 6 is 640 pixels across a 320 px panel, so pixel PAIRS are OR-ed --
       a rule taken from the previous port: a set bit in either lights the
       output pixel, which keeps one-pixel-wide rules visible where dropping
       every other column would erase half of them.
       Indexed by a NIBBLE (4 source pixels -> 2 output), so the table is 64
       bytes rather than the 1 KB a byte-indexed one would cost -- RAM_EMU has
       four figures of headroom, not five. */
    for (unsigned n = 0; n < 16; n++) {
        unsigned p0 = ((n >> 3) | (n >> 2)) & 1;
        unsigned p1 = ((n >> 1) | (n >> 0)) & 1;
        cga1_expand[n] = (uint32_t)((X86_GFX_CLUT_BASE + p0)
                                    | ((X86_GFX_CLUT_BASE + p1) << 8));
    }

    /* Bilevel row expansion: 0xFF per lit pixel, leftmost pixel in the low
       byte so a word store lands them left to right. */
    for (unsigned b = 0; b < 16; b++) {
        uint32_t m = 0;
        for (unsigned i = 0; i < 4; i++)
            if (b & (1u << i))
                m |= 0xFFu << (8 * i);
        text_mask4[b] = m;
    }
#if X86_TEXT_AA
    /* Anti-aliased row expansion: two bits per pixel out to one byte each. */
    for (unsigned b = 0; b < 256; b++) {
        uint32_t w = 0;
        for (unsigned i = 0; i < 4; i++)
            w |= (uint32_t)((b >> (2 * i)) & 3) << (8 * i);
        text_level4[b] = w;
    }
    for (unsigned g = 0; g < 256; g++) {
        uint8_t all = font4x8aa_cp437[g][0];
        aa_glyph_flat[g] = (all == 0x00 || all == 0xFF);
        for (unsigned y = 1; y < CELL_H; y++)
            if (font4x8aa_cp437[g][y] != all)
                aa_glyph_flat[g] = 0;
    }
#endif

    /* Power-on state: mode 4 graphics with the bright cyan/magenta/white
       palette, which is what the BIOS leaves behind. The guest overrides it
       through 0x3D8/0x3D9 and the CLUT follows. */
    x86_io.cga_mode = 0x0A;
    x86_io.cga_color_select = 0x30;
    x86_video_refresh_palette();
}

/* Map VRAM into the guest at 0xB8000. Fixed, not pooled: it is a device
   aperture that happens to be readable memory, and it must not move. */
int x86_video_map(void)
{
    int ok = x86_map_fixed(0xB8000u, cga_vram, X86_VRAM_BYTES);
    /* The mode 13h aperture, over the top of the open-bus filler that aliases
       the rest of the upper megabyte. It is mapped ALWAYS, not on the mode
       set: a guest may (and Wolf3D's setup code does) write pixels before it
       switches, and a mode set that had to remap memory would lose them. It
       costs nothing to leave mapped -- no mode but 13h reads it. */
    if (vga_aperture)
        ok &= x86_map_fixed(0xA0000u, vga_aperture, X86_VGA_APERTURE_BYTES);

    /* PIN the guest pages these occupy. They are display storage the blitter
       reads every frame; evicting one would be visible in the next frame, and
       the pager must be able to reject them in a single test rather than by
       knowing what they are. Pinning is by GUEST page number, so it survives
       the page being re-pointed at different host memory. */
    x86_pin_pages(0xB8000u >> FOLD_SHIFT, X86_VRAM_BYTES >> FOLD_SHIFT);
    if (vga_aperture)
        x86_pin_pages(0xA0000u >> FOLD_SHIFT,
                      X86_VGA_APERTURE_BYTES >> FOLD_SHIFT);
    return ok;
}

