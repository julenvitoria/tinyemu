/*
 * Text mode 3 is 80x25. At the CGA's own 8x8 cell that is 640x200 -- twice the
 * width of the panel -- so an 8 px cell can only ever show 40 of the 80
 * columns. That is not a "needs panning" inconvenience: a DOS full-screen UI
 * puts its frame in the MIDDLE of the 80 columns, so a 40-column window
 * anchored anywhere chops the picture in half. TOPBENCH's menu lives in
 * columns 25-52 and came out sliced down the middle at column 40.
 *
 * So the cell is 4 px wide (`font4x8.h`, generated by scripts/make_font.py):
 * 80 x 4 = 320 exactly, the whole guest screen, correctly framed, nothing
 * off-panel. Condensed glyphs are smaller but they are all there, and a UI you
 * can see all of beats half a UI in a larger face.
 */
#define TEXT_COLS       80
#define TEXT_ROWS       25
#define TEXT_VIS_COLS   80
#define CELL_W          4
#define CELL_H          8

/* ---------------------------------------------------------------------------
 * The mode set, and what selects it.
 *
 * Ported from the author's previous DOS core (dos_video.c) and the design in
 * references/8086tiny/docs/video/. Two rules carry over unchanged, and both are
 * corrections of things that were tried and failed there:
 *
 *   1. THE BDA IS AUTHORITATIVE for graphics-vs-text: 0040:0049 is the mode and
 *      0040:004A the column count. Port 0x3D8 is read for the things it alone
 *      knows (the palette variant), NEVER to decide the mode -- a program that
 *      sets its mode through INT 10h need never touch 0x3D8, and something in a
 *      DOS boot path leaves its graphics bit set at the prompt, which latches a
 *      "ports win" renderer into decoding text memory as 2 bpp.
 *   2. THE COLUMN COUNT SELECTS THE FONT: 80 -> the 4x8 cell, 40 -> the 8x8
 *      cell. Both are exactly 320 px wide, so 40-column modes 0/1 need no
 *      geometry of their own and no mode-number lookup.
 *
 * A mode we cannot render is REFUSED rather than accepted-and-ignored: a guest
 * drawing into memory nothing reads looks like a blank screen and reads like a
 * bug, whereas keeping the old mode up leaves the previous picture and a log
 * entry that names the mode.
 */
#define VM_TEXT   0     /* char+attr pairs at 0xB8000                      */
#define VM_CGA2   1     /* 320x200 2 bpp, two-bank interleave              */
#define VM_CGA1   2     /* 640x200 1 bpp, same interleave, decimated 2:1   */
#define VM_VGA8   3     /* 320x200 8 bpp LINEAR at 0xA0000 -- mode 13h     */
#define VM_EGA4   4     /* 320x200 4 bpp PLANAR at 0xA0000 -- mode 0Dh     */

typedef struct {
    uint8_t mode;       /* the BDA 0x449 value                             */
    uint8_t kind;
    uint8_t cols;       /* text columns -- of the mode, or of its TTY grid */
} x86_vmode;

/* Mode 7 is folded to 3: the B000:0 mono buffer is not backed, and the
   previous port's BIOS folds it for the same reason. */
static const x86_vmode vmodes[] = {
    { 0x00, VM_TEXT, 40 },
    { 0x01, VM_TEXT, 40 },
    { 0x02, VM_TEXT, 80 },
    { 0x03, VM_TEXT, 80 },
    { 0x04, VM_CGA2, 40 },
    { 0x05, VM_CGA2, 40 },
    { 0x06, VM_CGA1, 80 },
    /* EGA 0Dh. Its plane storage is an arena claim, so vmode_find() gates it on
       the claim being satisfiable the same way 13h is gated on its aperture.
       Modes 0Eh and 10h are deliberately absent: they need 16,000 and 28,000
       bytes per plane against the 8,192 offsets this partition holds, and a
       mode set that is accepted and cannot be rendered leaves the guest drawing
       into memory nothing reads. See 11-ega-planar.md, "Out of scope". */
    { 0x0D, VM_EGA4, 40 },
    { 0x13, VM_VGA8, 40 },
};

/* The active mode. Not static: the harness reads the byte to know which
   renderer to check against. `cur_desc` is never NULL -- every writer goes
   through mode_select(), which refuses a mode it has no descriptor for. */
uint8_t x86_video_mode_byte = 0x04;
#define video_mode x86_video_mode_byte
static const x86_vmode *cur_desc = &vmodes[4];      /* 0x04, power-on */

static const x86_vmode *vmode_find(uint8_t mode)
{
    if (mode == 0x07)                   /* mono text, folded to 3 */
        mode = 0x03;
    /* Mode 13h without its 64 KB aperture is not a mode we can render, so it
       is REFUSED here rather than adopted -- otherwise the guest draws into
       the open-bus filler and the symptom is a frozen screen with no error.
       This is the same rule as any other unrenderable mode; the only
       difference is that this one depends on an allocation. */
    if (mode == 0x13 && !x86_vga13_ok)
        return 0;
    /* EGA 0Dh needs plane storage out of the arena, and a REFUSAL MUST BE LOUD:
       "EGA needs N more bytes than exist" is actionable, "the screen is blank"
       is not. x86_arena_would_fit() runs the real placement without committing,
       so this cannot pass here and fail at the claim below. If the claim is
       already held (we are re-entering 0Dh) the dry run accounts for that --
       re-claiming an id releases the old claim first. */
    if (mode == 0x0D
        && (!x86_vga13_ok
            || !x86_arena_would_fit(X86_ARENA_ID_EGA, 1,
                                    4u * X86_EGA_PLANE_OFFSETS))) {
        x86_vga_ega_refused++;
        return 0;
    }
    for (unsigned i = 0; i < sizeof vmodes / sizeof vmodes[0]; i++)
        if (vmodes[i].mode == mode)
            return &vmodes[i];
    return 0;
}

