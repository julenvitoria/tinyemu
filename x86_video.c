static uint16_t text_scroll_col;    /* leftmost visible column */

/*
 * Leftmost visible column. All 80 columns now fit (4 px cells), so this is
 * always clamped to 0 and the cursor-following below is a no-op -- kept because
 * the window machinery is what a future wider cell or a 132-column mode would
 * need, and because `x86_video_pan` is part of the harness interface
 * (scripts/screenshot.py --pan, tests/test_text.py). -1 means "follow the
 * cursor"; any value is clamped to TEXT_COLS - TEXT_VIS_COLS.
 */
volatile int32_t x86_video_pan = -1;

/*
 * Adopt a mode WITHOUT touching guest VRAM. This is the renderer-selection
 * half: which blit runs, which font, which palette rule. It is what the
 * per-frame BDA re-read calls, and clearing VRAM there would wipe the screen of
 * a guest that set the mode by writing the BDA itself.
 */
/*
 * Give the planar adapter the storage the mode being adopted needs, and take
 * back what it does not.
 *
 * PEAK DEMAND, NOT SUM. The modes are mutually exclusive -- a guest is in 13h
 * or 0Dh, never both -- so one 32,768-byte arena block serves whichever is up,
 * under two different claim ids so a probe can name the holder. With CGA
 * (32,768) and the 13h aperture (65,536) held out of a 143,360-byte arena there
 * are 45,056 bytes free, and this is 32,768 of them: 12,288 to spare either way.
 *
 *   Mode Y   the 64 KB aperture IS the plane storage (one aliased page), and
 *            the block is the OFF-SCREEN cache at 0xC300 upward. Losing it is a
 *            DEGRADATION, not a refusal: offsets with no storage draw nothing,
 *            which is what an unfitted card does.
 *   0Dh      the aperture is the CPU read shadow and the block is the planes.
 *            Losing it IS a refusal -- there is nowhere for a pixel to go.
 */
/*
 * ---- THE CGA LOAN, AND THE COMPACTION IT PAYS FOR -------------------------
 *
 * While a planar mode is armed the 32 KB CGA claim is DEAD WEIGHT: text and
 * CGA graphics cannot be on screen at the same time as 0Dh, which is the whole
 * premise of the arena ("the peak demand is the LARGEST mode rather than the
 * sum", x86_arena.h). So 0Dh borrows it and gives it back on the way out.
 *
 * Releasing it is not enough by itself, and the arithmetic says why. The arena
 * is 35 pages, claimed in init order: CGA at pages 0-7, the 13h aperture at
 * 8-23, 11 pages free at 24-34. Dropping CGA leaves TWO holes (8 pages and 11
 * pages) and the planes are ONE interleaved block -- plane p at offset a lives
 * at planes[4a+p] -- so a split card is not addressable and the best a release
 * alone buys is 11,264 offsets. The aperture is therefore RE-CLAIMED first,
 * which first-fits it into the vacated bottom and leaves one 19-page run:
 *
 *      143,360 arena - 65,536 aperture = 77,824 = 19,456 plane offsets
 *      19,456 / 64 B per row (Keen's CRTC Offset 0x20) = 304 rows > 200
 *
 * against the 8,192 offsets (128 rows) that cut Keen's intro off three
 * quarters of the way up. It is still not the 65,536 offsets/plane the Galaxy
 * engine's off-screen tile cache actually wants (11-ega-planar.md, "Keen 4
 * needs a 256 KB card"), so expect a whole frame with wrong tiles in it, not a
 * pixel-correct one.
 *
 * CONTENTS ARE NOT PRESERVED, and that is safe by exactly one mechanism: every
 * return to text goes through INT 10h AH=00, and x86_video_set_mode() clears
 * the cell buffer to 0x0720 after mode_select(). Nothing else may assume it,
 * so a re-claim that lands on different pages is blanked HERE too -- a guest
 * that drives the BDA directly (mode_sync_from_bda -> mode_select, which does
 * NOT clear) would otherwise read plane bytes as characters.
 */
static uint8_t cga_lent;            /* the CGA claim is on loan to 0Dh */

/*
 * May the CGA cell/pixel buffer be touched at all?
 *
 * WHILE THE LOAN IS OUT, cga_vram POINTS AT THE PLANES. Every writer below --
 * the mode-set clear, the graphics scroll, gfx_putchar(), putpixel -- runs in
 * ANY non-text mode, 0Dh included, so without this they would scribble CGA
 * bytes over the EGA card and the corruption would read as a planar bug. None
 * of them loses anything by standing down: their output is a CGA-format screen
 * that no 0Dh renderer reads.
 */
static int cga_storage_ok(void)
{
    return cga_vram && !cga_lent;
}

static void cga_storage_lend(void)
{
    if (cga_lent || !x86_arena_held(X86_ARENA_ID_CGA))
        return;                     /* not arena-backed: nothing to lend */
    x86_arena_release(X86_ARENA_ID_CGA);
    cga_lent = 1;
}

static void cga_storage_reclaim(void)
{
    void *blk = NULL;

    if (!cga_lent)
        return;
    if (x86_arena_claim(X86_ARENA_ID_CGA, 1, X86_VRAM_BYTES, &blk) != 0) {
        /* Loud, and it must also STOP: cga_vram still points into pages the
           arena now considers free, and claiming anything else would alias
           them onto the text buffer. */
        x86_video_log_event(7, 0, 0);
        return;
    }
    cga_lent = 0;
    cga_vram = (uint8_t *)blk;
    x86_map_fixed(0xB8000u, cga_vram, X86_VRAM_BYTES);
    memset(cga_vram, 0, X86_VRAM_BYTES);
    for (unsigned i = 0; i < TEXT_COLS * TEXT_ROWS; i++)
        ((uint16_t *)cga_vram)[i] = 0x0720;
}

/* Pull the 13h aperture down to the bottom of the arena so the planes get one
   run rather than two. A re-claim releases the old claim first, so this is a
   no-op the second time. Its contents are the CPU read shadow, which
   x86_vga_planar_arm() rebuilds. */
static void aperture_compact(void)
{
    void *blk = NULL;

    if (!x86_arena_held(X86_ARENA_ID_VGA13))
        return;                     /* not arena-backed: leave it alone */
    if (x86_arena_claim(X86_ARENA_ID_VGA13, 1, X86_VGA_APERTURE_BYTES,
                        &blk) != 0)
        return;                     /* the old placement survives intact */
    if ((uint8_t *)blk == vga_aperture)
        return;
    vga_aperture = (uint8_t *)blk;
    x86_vga_planar_aperture = vga_aperture;
    x86_map_fixed(0xA0000u, vga_aperture, X86_VGA_APERTURE_BYTES);
    memset(vga_aperture, 0, X86_VGA_APERTURE_BYTES);
}

/* The largest card the arena will give, in plane offsets, bounded by what the
   mode can ADDRESS (the A segment decodes 64 KB per plane) and by page
   granularity. Deliberately a maximum and not a minimum: 11-ega-planar.md
   warns that sizing 0Dh to the visible page is a partial fix at best, because
   Keen's tile cache lives off-screen. 0 means not even the old size fits. */
#define X86_EGA_PLANE_MAX   0x10000u        /* 64 KB/plane, a 256 KB card */
#define EGA_OFFS_PER_PAGE   (X86_ARENA_PAGE / 4u)

static uint32_t ega_fit_offsets(void)
{
    uint32_t off = x86_arena_largest / 4u;

    if (off > X86_EGA_PLANE_MAX)
        off = X86_EGA_PLANE_MAX;
    off &= ~(EGA_OFFS_PER_PAGE - 1u);
    while (off >= X86_EGA_PLANE_OFFSETS) {
        if (x86_arena_would_fit(X86_ARENA_ID_EGA, 1, 4u * off))
            return off;
        off -= EGA_OFFS_PER_PAGE;
    }
    return 0;
}

/* The card actually fitted, in plane offsets. Host-visible because "how big is
   the card" is the first question a clipped picture raises. */
volatile uint32_t x86_vga_ega_card_offsets;

/*
 * The Mode Y off-screen cache, sized to the arena rather than fixed.
 *
 * It was a flat 8,192 offsets, covering 0xC300..0xE2FF. Measured on hardware,
 * WOLF3D's episode-select screen threw away 16,896 stores above 0xE300 and
 * missed 4,928 latch loads, and the picture said the same thing: perfect text
 * (drawn straight to the visible page) around six thumbnails of pure noise
 * (cached off-screen, then blitted out with latch copies). Wolf3D's off-screen
 * writes reach 0xEBFF, so the cache has to run to 0xEC00 -- 10,496 offsets --
 * and the shipping layout leaves 12,288 bytes of arena unclaimed.
 *
 * So it is fitted the way the EGA card is: ask for the most that could ever be
 * addressed and walk down a page at a time until the arena takes it. A
 * re-claim releases the old block INSIDE claim_inner(), so the cache's own
 * 32 KB is part of what the larger claim is placed into -- and this is exactly
 * the fragmentation subtlety the EGA work found, where releasing a claim by
 * hand leaves two holes because claims sit in init order. `x86_arena_largest`
 * is the number that says whether it worked.
 *
 * The maximum is what the mode can ADDRESS, not what a title wants: the A
 * segment decodes 64 KB per plane, so 0xC300 + 0x3D00 lands exactly on 0x10000
 * and there is nothing above it to cache.
 */
#define X86_MODEY_CACHE_MAX   0x3D00u       /* 0x10000 - X86_MODEY_CACHE */
#define MODEY_OFFS_PER_PAGE   (X86_ARENA_PAGE / 4u)

/* The NEGATIVE CONTROL for the fit: pin the cache back to the fixed 8,192
   offsets it shipped as. scripts/run_planar_controls.py builds this arm and
   requires tests/test_video.py's Mode Y check to FAIL on it -- without that,
   "the cache reaches the top of the window" is a check that cannot fail. */
#ifndef X86_MODEY_CACHE_NEGCTL
#define X86_MODEY_CACHE_NEGCTL 0
#endif

static uint32_t modey_fit_offsets(void)
{
    if (X86_MODEY_CACHE_NEGCTL)
        return x86_arena_would_fit(X86_ARENA_ID_SPARE, 1,
                                   4u * X86_MODEY_CACHE_OFFSETS)
               ? X86_MODEY_CACHE_OFFSETS : 0u;

    /* The FIRST try is the exact maximum, not the maximum rounded DOWN to a
       page. 0x3D00 offsets is 62,464 bytes, which the arena rounds up to 16
       pages internally; masking down first asks for 15,360 offsets instead and
       leaves the top 256 offsets of the window uncached -- measured as 256
       discarded stores at 0xFF00..0xFFFF with 16 KB of arena still free. */
    uint32_t off = X86_MODEY_CACHE_MAX;

    while (off >= MODEY_OFFS_PER_PAGE) {
        if (x86_arena_would_fit(X86_ARENA_ID_SPARE, 1, 4u * off))
            return off;
        off = (off - 1u) & ~(MODEY_OFFS_PER_PAGE - 1u);
    }
    return 0;
}

/*
 * Borrow what the policy allows, fit the card to it, claim it, publish it.
 *
 * Split out of the 0Dh arm of planar_storage_follow() because it is now called
 * from TWO places: mode adoption, and the once-per-frame policy tick that
 * re-fits the card when the pager's measured working set has moved. Every
 * caller must have RELEASED the EGA claim first -- x86_arena_largest cannot
 * know that a re-claim would free the card it is being asked to replace.
 *
 * BORROW FROM GUEST RAM. The arena is 143,360 B and 100% used in 0Dh while the
 * guest's frame pool has idle frames; PLAN.md Phase 3 always meant the extra
 * plane storage to come from there. The floor is one page past the best run
 * the arena already has -- donating to build a card no bigger than the one
 * that already fits would shrink the guest for nothing. How MANY frames may go
 * is x86_pager_policy_reserve()'s answer and it changes as the guest runs; see
 * x86_pager.h.
 */
static void ega_card_place(int may_borrow)
{
    void *blk = NULL;
    uint32_t floor = x86_arena_largest + X86_ARENA_PAGE;

    if (floor < 4u * X86_EGA_PLANE_OFFSETS)
        floor = 4u * X86_EGA_PLANE_OFFSETS;
    if (may_borrow && floor <= 4u * X86_EGA_PLANE_MAX)
        x86_pager_donate_upto(4u * X86_EGA_PLANE_MAX, floor);

    uint32_t offs = ega_fit_offsets();
    if (offs && x86_arena_claim(X86_ARENA_ID_EGA, 1, 4u * offs, &blk) == 0) {
        x86_vga_ega_set_planes(blk, offs);
        x86_vga_ega_card_offsets = offs;
        x86_video_log_event(8, offs >> 8, 0);
    } else {
        /* Loud: the mode is about to be refused, and the counter plus the
           arena deficit are what say why. */
        x86_vga_ega_set_planes(NULL, 0);
        x86_vga_ega_card_offsets = 0;
        x86_vga_ega_refused++;
        x86_video_log_event(7, 0, 1);
    }
}

static void planar_storage_follow(uint8_t kind)
{
    void *blk = NULL;

    if (kind == VM_EGA4) {
        x86_arena_release(X86_ARENA_ID_SPARE);
        x86_vga_modey_set_cache(NULL, 0);
        x86_arena_release(X86_ARENA_ID_MODEYP);
        x86_vga_modey_set_pages(NULL, NULL);
        /* Release BEFORE measuring: x86_arena_largest cannot know that a
           re-claim would free the card we are replacing. */
        x86_arena_release(X86_ARENA_ID_EGA);
        x86_vga_ega_set_planes(NULL, 0);
        cga_storage_lend();
        aperture_compact();
        ega_card_place(1);
        return;
    }

    x86_arena_release(X86_ARENA_ID_EGA);
    x86_vga_ega_set_planes(NULL, 0);
    x86_vga_ega_card_offsets = 0;
    /* Mode Y's real pages live in the DONATED extent, so they must go back
       before the reclaim below -- a reclaim is refused while the arena still
       holds a page inside it, and the frames would stay lent for the rest of
       the session (x86_pg_reclaim_busy says so when this is got wrong). */
    x86_arena_release(X86_ARENA_ID_MODEYP);
    x86_vga_modey_set_pages(NULL, NULL);
    /* Give the borrowed frames back BEFORE anything else claims: a reclaim is
       refused while the arena still holds a page in the donated extent, and
       every claim below is exactly such a claim. The CGA reclaim itself moved
       into the arms below, because the cache has to be released first -- see
       the comment there. */
    x86_pager_reclaim_from_arena();
    if (kind != VM_VGA8) {
        /* RELEASE THE CACHE BEFORE RECLAIMING CGA, not after. Now that 13h
           lends the CGA claim out as well, the cache is 62,464 bytes and the
           arena has only 15,360 free while it is held -- so reclaiming first
           cannot place the 32,768-byte CGA block, leaves the loan outstanding,
           and the old early return then never released the cache either. The
           mode goes back to text with no text buffer and a cache nobody owns.
           Caught by tests/test_video.py's modeyfit arm, which is why that arm
           checks the way BACK as well as the way in. */
        x86_arena_release(X86_ARENA_ID_SPARE);
        x86_vga_modey_set_cache(NULL, 0);
        cga_storage_reclaim();
        return;
    }
    /*
     * 13h LENDS THE CGA CLAIM OUT TOO, for the same reason 0Dh does.
     *
     * Measured: with the cache fitted out of unclaimed arena alone it reaches
     * 11,264 offsets (to 0xEEFF) and WOLF3D still discards 4,352 stores --
     * x86_vga_modey_lost_lo/_hi read 0xEF00 and 0xFFFF, i.e. the title writes
     * cached pictures right up to the top of the window and the shortfall is
     * exactly the tail. Covering it needs 62,464 bytes against the 45,056 that
     * exist without the loan.
     *
     * Nothing is lost by lending. The CGA claim holds the 80x25 cell buffer and
     * the mode-4 pixel planes; in 13h neither is displayed -- every writer of
     * it already stands down on cga_storage_ok(), and the renderer reads the
     * aperture. Contents are not preserved, which is safe by the same single
     * mechanism as 0Dh's loan: every return to text goes through INT 10h AH=00
     * and x86_video_set_mode() clears the cell buffer after mode_select().
     */
    x86_arena_release(X86_ARENA_ID_SPARE);
    x86_vga_modey_set_cache(NULL, 0);
    cga_storage_lend();
    /* Compact BEFORE measuring. Releasing a claim leaves two holes, because
       claims sit in init order -- the EGA work found this the hard way, and
       the arithmetic working out is not evidence that the RUN exists.
       x86_arena_largest is. */
    aperture_compact();
    /* The cache is claimed when 13h is ADOPTED, not when the guest unchains:
       unchaining happens inside an OUT to 0x3C4 and an arena claim there would
       put a placement walk on an I/O path, for storage that is only ever needed
       by a mode already up. */
    uint32_t offs = modey_fit_offsets();
    if (offs && x86_arena_claim(X86_ARENA_ID_SPARE, 1, 4u * offs, &blk) == 0)
        x86_vga_modey_set_cache(blk, offs);
    else
        x86_vga_modey_set_cache(NULL, 0);

    /*
     * REAL PAGE STORAGE FOR MODE Y -- the last unfixed cause of Wolf3D's
     * corrupted gameplay picture, and the reason donation and eviction were
     * built.
     *
     * Three display starts (0x0000, 0x4100, 0x8200) fold onto ONE page's bytes
     * without this, so the panel shows page N while the raycaster draws page
     * N+1 over it. It is not tearing and no presentation policy fixes it; it
     * needs 64 KB per extra page. The arena has ~15 KB free here with the cache
     * fitted, so every byte comes from the pager's idle frames.
     *
     * TWO EXTRA PAGES, ASKED FOR AS A LADDER. Two (131,072 B, three real pages)
     * is the hardware layout; one (65,536 B, two real pages) already removes
     * the draw-over-displayed hazard, which IS the defect -- WOLF3D never draws
     * into the page it is displaying, only into the next one. Below that the
     * aliased fold stays, and x86_vga_modey_alias_hits is what says so.
     *
     * HOW MANY EXTRA PAGES TO ASK FOR IS A KNOB, AND IT HAD TO BECOME ONE.
     *
     * This used to ask for two unconditionally, on a measurement that silicon
     * has since falsified. The old note read "WOLF3D peaks at 104 of 160
     * frames resident, so 32 donated frames leave 128 -- above the working
     * set, no thrash". MEASURED ON HARDWARE, 3 minutes of real play:
     *
     *   x86_pg_frames_total  126        (160 less the 34 donated)
     *   x86_pg_evictions     368        monotonic, never settling
     *   x86_pg_fill_file     334        pages read straight back IN
     *   x86_pg_exhausted     0          allocation never fails
     *
     * 368 out against 334 back in is not a working set paged out once. It is
     * clock replacement cycling on a pool slightly too small, and every
     * guest_fps_achieved collapse in that run lines up with an eviction burst.
     * The 104-frame peak was measured before the working set this title
     * actually has.
     *
     * So the ladder's rung is now X86_MODEY_EXTRA_PAGES, because the trade is
     * between a RENDERING defect and a PAGING one and the only honest way to
     * settle it is to build both arms and grade them against the WOLF3D
     * golden. Two pages (131,072 B, 32 frames) is the hardware layout; ONE
     * (65,536 B, 16 frames) already removes the draw-over-displayed hazard,
     * which IS the defect -- WOLF3D never draws into the page it is
     * displaying, only into the next one -- and hands 16 frames back to the
     * guest. Zero keeps the aliased fold and x86_vga_modey_alias_hits says so.
     *
     * The gate on any rung is the golden at 0.000% plus alias_hits at 0. Do
     * not lower it on a frame-rate argument alone.
     */
#ifndef X86_MODEY_EXTRA_PAGES
#define X86_MODEY_EXTRA_PAGES 2u
#endif
    /*
     * DONATE ONLY WHAT THE ARENA CANNOT ALREADY PLACE.
     *
     * x86_pager_donate_upto() is unconditional -- it takes the frames whether
     * or not they were needed. That is invisible today, because the 13h
     * aperture eats 65,536 of the arena's 143,360 bytes and there is never a
     * run for an extra page, so the answer is always "donate". It stops being
     * invisible the moment anything frees arena (the aperture moving to DTCM
     * was tried and does not fit -- src/main.c -- but the EGA/cache fits move
     * too), and donating on top of a run the arena already had would hand the
     * guest's frames away for nothing.
     *
     * x86_arena_would_fit() is the right question and x86_arena_free is not:
     * a claim needs a CONTIGUOUS run and releasing a claim leaves holes. That
     * is the same trap aperture_compact() exists for, and the arithmetic
     * working out has never been evidence that the run exists.
     *
     * MEASURED NO-OP TODAY: at the shipping rung the would_fit test is false
     * and the donation happens exactly as before (x86_pg_frames_total 126).
     */
    if (X86_MODEY_EXTRA_PAGES
        && !x86_arena_would_fit(X86_ARENA_ID_MODEYP, X86_MODEY_EXTRA_PAGES,
                                X86_MODEY_PAGE_BYTES))
        x86_pager_donate_upto(X86_MODEY_EXTRA_PAGES * X86_MODEY_PAGE_BYTES,
                              X86_MODEY_PAGE_BYTES);
    void *pg[2] = { NULL, NULL };
    if (X86_MODEY_EXTRA_PAGES >= 2u
        && x86_arena_claim(X86_ARENA_ID_MODEYP, 2, X86_MODEY_PAGE_BYTES, pg) == 0)
        x86_vga_modey_set_pages(pg[0], pg[1]);
    else if (X86_MODEY_EXTRA_PAGES >= 1u
             && x86_arena_claim(X86_ARENA_ID_MODEYP, 1, X86_MODEY_PAGE_BYTES,
                                pg) == 0)
        x86_vga_modey_set_pages(pg[0], NULL);
    else
        /* Loud by construction: x86_arena_deficit holds what the last refusal
           wanted and x86_vga_modey_pages stays 1. */
        x86_vga_modey_set_pages(NULL, NULL);
    x86_video_log_event(9, x86_vga_modey_pages, 0);
}

/*
 * ---------------------------------------------------------------------------
 * THE DYNAMIC SIDE OF THE CARD: re-fit it as the guest's working set moves.
 *
 * Sizing the card ONCE, at mode adoption, is what made "EGA or frames" look
 * like a choice. It is not one: KEEN4's intro is idle in RAM and wants every
 * plane offset it can get, its gameplay wants its frames back, and both facts
 * are true of the same title ten seconds apart. So the fit is re-evaluated,
 * once per frame, against a reserve the pager MEASURES (x86_pager.h).
 *
 * WHERE THIS IS ALLOWED TO RUN, and it is the whole safety argument:
 *
 *  - Once per FRAME, from the top of the render, BEFORE anything has read the
 *    card this frame and before mode_sync_from_bda() can adopt a new mode.
 *    Never mid-frame, never per access -- the cycle budget in CLAUDE.md is not
 *    negotiable and a placement walk is not a per-store cost.
 *  - A shrink RELEASES THE EGA CLAIM FIRST and only then reclaims. A reclaim
 *    while the arena still holds a page inside the donated extent is refused
 *    (x86_pg_reclaim_busy) and the frames stay lent for the session; the Mode Y
 *    arm below gives the real pages back for exactly the same reason.
 *  - The card's CONTENTS DO NOT SURVIVE a re-fit -- the claim moves, and
 *    x86_vga_planar_arm() zeroes planes and aperture on the way back in. That
 *    is a frame of blank card until the guest redraws, and it is the price of
 *    handing frames back at all. It is paid only when the policy actually
 *    fires, which on a title that never comes under pressure is never.
 *
 * The GROW arm is deliberately more timid than the shrink arm: a shrink is
 * correctness (the alternative is 433 ms pagefile writes inside the frame
 * loop), a grow is picture quality, so it needs a whole second of quiet AND a
 * gain of at least one arena page before it will spend a card's contents on it.
 */
void x86_video_policy_tick(void)
{
    int act = x86_pager_policy_tick();

    if (act == X86_PG_POLICY_HOLD || !cur_desc)
        return;

    if (cur_desc->kind == VM_VGA8) {
        /*
         * MODE Y. The card here is the real display pages, and they are not
         * re-fittable mid-mode: vga_cell() folds a display start onto page
         * storage that the raycaster is drawing into, so growing one in would
         * hand the guest a page full of somebody else's bytes. Only the shrink
         * arm exists, and it is the one that matters -- it is the path back
         * out of a level-load stall. At the shipping rung the arena places the
         * extra page with no frames donated at all, so this never fires.
         */
        if (act != X86_PG_POLICY_SHRINK || !x86_pg_donated)
            return;
        x86_arena_release(X86_ARENA_ID_MODEYP);
        x86_vga_modey_set_pages(NULL, NULL);
        x86_pager_reclaim_from_arena();
        x86_video_log_event(9, x86_vga_modey_pages, 2);
        return;
    }

    if (cur_desc->kind != VM_EGA4)
        return;

    if (act == X86_PG_POLICY_SHRINK) {
        if (!x86_pg_donated)
            return;                     /* nothing lent: nothing to give back */
    } else {
        /* GROW is permission, not an instruction: only spend the card's
           contents when a bigger one demonstrably fits. x86_arena_largest is
           already counted by ega_fit_offsets(); what is new is the headroom. */
        uint32_t head = x86_pager_policy_headroom();
        uint32_t have = 4u * x86_vga_ega_card_offsets;
        if (have >= 4u * X86_EGA_PLANE_MAX)
            return;                     /* the mode cannot address more */
        if (head < have + X86_ARENA_PAGE)
            return;                     /* no gain worth a blank frame for */
    }

    /* Disarm, release, hand the frames back, re-fit from scratch. Both
       directions go through the same sequence: after the reclaim the state is
       exactly what a fresh mode set would find, and the reserve in force is
       what decides how much of it goes back out again. */
    x86_vga_planar_arm(0);
    x86_arena_release(X86_ARENA_ID_EGA);
    x86_vga_ega_set_planes(NULL, 0);
    x86_pager_reclaim_from_arena();
    aperture_compact();
    /* A SHRINK BORROWS NOTHING. Re-donating inside the same refit is what a
       first draft did, and MEASURED on KEEN4 it cost 9 evictions instead of 2:
       the reserve had risen, so the smaller donation was taken and then had to
       be recalled again one tick later, and every hop paid its own writebacks.
       A shrink goes straight to the arena-only card; the grow arm is the only
       thing that lends, and it needs a second of quiet first. */
    ega_card_place(act == X86_PG_POLICY_GROW);
    if (!x86_vga_planar_arm(1))
        x86_video_log_event(7, 0, 2);   /* no card at all: loud, not silent */
}

static int mode_select(uint8_t mode)
{
    const x86_vmode *d = vmode_find(mode);
    if (!d) {
        x86_video_log_event(5, mode, video_mode);   /* refused; old mode stays */
        return 0;
    }
    if (d == cur_desc && mode == video_mode)
        return 1;

    planar_storage_follow(d->kind);
    /* Disarm FIRST, unconditionally: leaving Mode Y armed into a text mode set
       would put every 0xB8000-adjacent store through the adapter. Then arm 0Dh
       -- and if the adapter cannot take it even now, refuse rather than adopt a
       mode whose stores have nowhere to land. */
    x86_vga_modey_arm(0);
    if (d->kind == VM_EGA4) {
        if (!x86_vga_planar_arm(1)) {
            x86_video_log_event(5, mode, video_mode);
            planar_storage_follow(cur_desc->kind);   /* put the old mode back */
            return 0;
        }
    } else {
        x86_vga_planar_arm(0);
    }

    x86_video_log_event(1, d->cols, mode);
    cur_desc = d;
    video_mode = mode;
    /* A real VGA BIOS programs the CRTC on every mode set. Chained 13h does not
       need it; a title that unchains without setting the Offset itself does. */
    x86_vga_crtc_preset(mode);
    x86_video_refresh_palette();
    return 1;
}

/*
 * INT 10h AH=00. The mode set half: adopt the mode AND clear the display, which
 * is what the call promises and what mode_select() deliberately does not do.
 */
void x86_video_set_mode(uint8_t mode)
{
    /* Tag 6 BEFORE anything else: a set to the mode already up adopts nothing
       (mode_select() short-circuits) and so logs no tag 1, yet it still CLEARS
       the display -- which is the loudest thing this call does. Without this
       entry a screen that went blank between two samples has no cause in the
       ring at all, and the blank reads as a renderer fault. Measured: Keen 4's
       banner is erased by its SECOND INT 10h AH=00 AL=03h, and only this tag
       shows that it happened. */
    x86_video_log_event(6, mode, video_mode);
    if (!mode_select(mode))
        return;
    cur_row = cur_col = 0;
    text_scroll_col = 0;
    if (!cga_storage_ok()) {
        /* 0Dh has the CGA pages. The 13h aperture is still separate storage
           and still has to be cleared below. */
        if (cur_desc->kind == VM_VGA8 && vga_aperture)
            memset(vga_aperture, 0, X86_VGA_APERTURE_BYTES);
        x86_video_refresh_palette();
        return;
    }
    memset(cga_vram, 0, X86_VRAM_BYTES);
    /* The 13h aperture is separate storage, so clearing CGA VRAM does not
       touch it. A guest that sets 13h expects a blank screen, and leaving the
       previous title's pixels there is the "mode set did nothing" picture. */
    if (cur_desc->kind == VM_VGA8 && vga_aperture)
        memset(vga_aperture, 0, X86_VGA_APERTURE_BYTES);
    if (cur_desc->kind == VM_TEXT) {
        /* Text mode: blank cells are space on black, not zero bytes -- a zero
           attribute renders black-on-black and hides everything written
           before the guest sets its own colours. */
        uint16_t *cell = (uint16_t *)cga_vram;
        for (unsigned i = 0; i < TEXT_COLS * TEXT_ROWS; i++)
            cell[i] = 0x0720;
    }
    x86_video_refresh_palette();
}

/*
 * Follow the BIOS Data Area. Called once per frame, which is where the
 * previous port does its detection too -- per-instruction polling buys nothing
 * a frame-rate check does not.
 *
 * Two guards, and they are the difference between this being robust and being
 * a hardware-only failure. The BDA page may not be backed at all (x86_bios.c
 * tolerates that everywhere else, and on silicon it is an open question), and
 * an unbacked or blank page reads mode 0 / cols 0 -- which is a VALID mode
 * number and would silently reinterpret every screen as 40-column text. So the
 * columns must ALSO be sane, and 0 is not.
 */
static void mode_sync_from_bda(void)
{
    uint8_t bmode; uint16_t bcols;

    if (!x86_bios_bda_video(&bmode, &bcols))
        return;
    if (bcols != 40 && bcols != 80)
        return;                         /* not a BDA anyone is maintaining */
    if (bmode == video_mode)
        return;
    mode_select(bmode);
}

uint8_t x86_video_mode(void) { return video_mode; }

void x86_video_set_cursor(uint8_t col, uint8_t row)
{
    cur_col = col; cur_row = row;
    if (cur_col < text_scroll_col)
        text_scroll_col = cur_col;
    else if (cur_col >= text_scroll_col + TEXT_VIS_COLS)
        text_scroll_col = (uint16_t)(cur_col - TEXT_VIS_COLS + 1);
}

uint16_t x86_video_get_cursor(void)
{
    return (uint16_t)((cur_row << 8) | cur_col);
}

/* The cell buffer's row stride is the ACTIVE column count: a 40-column mode
   packs 40 cells per row, so indexing it at 80 reads the middle of row 2. */
static uint16_t *text_cell(unsigned row, unsigned col)
{
    return (uint16_t *)cga_vram + row * cur_desc->cols + col;
}

/* The cell under the cursor, character in the low byte and attribute in the
   high byte -- the layout INT 10h AH=08 returns in AX. */
uint16_t x86_video_read_cell(void)
{
    /* A graphics screen has no cell to read back -- the pixels under the
       cursor are not a character. A blank is what a real BIOS's own read-back
       buffer would hold, and it is what a program probing the display can act
       on; returning pixel bytes would have it believe them. */
    if (!cga_vram || !x86_video_is_text())
        return 0x0720;
    return *text_cell(cur_row, cur_col);
}

/* ---------------------------------------------------------------------------
 * CHARACTER OUTPUT IN A GRAPHICS MODE, which is the whole of the reported bug.
 *
 * MEASURED, Alley Cat under gwemu (`x86_video_mode_log`, tag 4): the guest sets
 * mode 4 through INT 10h -- correctly, and both our mode byte and BDA 0040:0049
 * follow it -- and THEN prints "Do you want to use a joystick (Y/N)?" through
 * the BIOS/DOS character path. Every one of those 36 characters was stored as a
 * char/attr PAIR into 0xB8000. In mode 4 those two bytes are not a cell, they
 * are eight pixels, so the mode-4 blitter drew 72 bytes of prompt as 288 pixels
 * of confetti across guest scanline 0 and nothing else. The mode switch was
 * never the defect; the characters were simply never rasterised.
 *
 * A real BIOS renders the glyph as an 8x8 BITMAP in a graphics mode and only
 * stores char/attr in a text one. The previous port hit this on the same title
 * and fixed it the same way (references/8086tiny/8086tiny.c dos_gfx_putchar,
 * bios.asm:2779). Two details taken straight from it, both of which are only
 * obvious once they have been got wrong:
 *
 *   * A glyph is EIGHT scanlines, so it straddles both interleave banks. Get
 *     that wrong and text appears with every other scanline missing, which
 *     reads as a blit bug rather than as this.
 *   * COLOUR 0 HAS TO MEAN VISIBLE. DOS's console output never sets a
 *     foreground colour, and taking the zero literally renders the prompt in
 *     the background colour -- invisible, i.e. the same symptom as not drawing
 *     it, chased twice.
 *
 * It is routed from ALL of the character paths here, not just teletype: the
 * previous port scoped its fix to INT 10h AH=0Eh and left AH=09h/0Ah and the
 * scroll routines storing pairs into pixel memory (its own notes carry that as
 * an open defect). Ours are three C functions over one cursor, so covering
 * them costs nothing but doing it.
 */
static void gfx_putchar(uint8_t ch, uint8_t colour, unsigned col, unsigned row)
{
    const unsigned char *g = x86_font8x8()[ch];
    unsigned wide = (cur_desc->kind == VM_CGA2);

    if (row >= TEXT_ROWS || col >= cur_desc->cols || !cga_storage_ok())
        return;

    if (wide) {
        unsigned pix = colour & 3;
        if (!pix)
            pix = 3;
        for (unsigned line = 0; line < CELL_H; line++) {
            unsigned y = row * CELL_H + line;
            uint8_t *o = cga_vram + ((y & 1) ? CGA_PLANE_ODD : 0)
                       + (y >> 1) * CGA_ROW_BYTES + col * 2;
            unsigned bits = g[line];
            /* Two bytes of 2 bpp per glyph row. Our font is bit-0-leftmost
               (Hepper's order, see x86_osk.c); CGA packs the leftmost pixel in
               the HIGH bits, so pixel p goes to shift 6-2p. */
            for (unsigned half = 0; half < 2; half++) {
                uint8_t b = 0;
                for (unsigned p = 0; p < 4; p++)
                    if (bits & (1u << (half * 4 + p)))
                        b |= (uint8_t)(pix << (6 - 2 * p));
                o[half] = b;
            }
        }
    } else {
        for (unsigned line = 0; line < CELL_H; line++) {
            unsigned y = row * CELL_H + line;
            uint8_t *o = cga_vram + ((y & 1) ? CGA_PLANE_ODD : 0)
                       + (y >> 1) * CGA_ROW_BYTES + col;
            /* 1 bpp: the row IS the byte -- once reversed, because the font is
               bit-0-leftmost and the adapter is bit-7-leftmost. */
            unsigned bits = g[line], b = 0;
            for (unsigned p = 0; p < 8; p++)
                if (bits & (1u << p))
                    b |= 0x80u >> p;
            *o = (uint8_t)b;
        }
    }
}

/* Scroll a graphics screen: a text "row" is EIGHT SCANLINES of pixels here, not
   160 bytes of cells. Both banks move, so this walks scanlines rather than
   memmoving the buffer. */
static void gfx_scroll(uint8_t lines)
{
    unsigned shift = lines * CELL_H;

    for (unsigned y = 0; y + shift < CGA_HEIGHT; y++) {
        uint8_t *d = cga_vram + ((y & 1) ? CGA_PLANE_ODD : 0)
                   + (y >> 1) * CGA_ROW_BYTES;
        unsigned s = y + shift;
        const uint8_t *sp = cga_vram + ((s & 1) ? CGA_PLANE_ODD : 0)
                          + (s >> 1) * CGA_ROW_BYTES;
        memcpy(d, sp, CGA_ROW_BYTES);
    }
    for (unsigned y = CGA_HEIGHT - shift; y < CGA_HEIGHT; y++)
        memset(cga_vram + ((y & 1) ? CGA_PLANE_ODD : 0)
               + (y >> 1) * CGA_ROW_BYTES, 0, CGA_ROW_BYTES);
}

void x86_video_scroll(uint8_t lines, uint8_t attr)
{
    unsigned cols = cur_desc->cols;

    if (!cga_storage_ok())
        return;                 /* the planes hold those pages: see the loan */
    if (!x86_video_is_text()) {
        if (lines == 0 || lines >= TEXT_ROWS)
            memset(cga_vram, 0, X86_VRAM_BYTES);
        else
            gfx_scroll(lines);
        return;
    }
    if (lines == 0 || lines >= TEXT_ROWS) {
        uint16_t *c = (uint16_t *)cga_vram;
        for (unsigned i = 0; i < cols * TEXT_ROWS; i++)
            c[i] = (uint16_t)(0x20 | (attr << 8));
        return;
    }
    memmove(cga_vram, cga_vram + lines * cols * 2,
            (TEXT_ROWS - lines) * cols * 2);
    uint16_t *c = text_cell(TEXT_ROWS - lines, 0);
    for (unsigned i = 0; i < lines * cols; i++)
        c[i] = (uint16_t)(0x20 | (attr << 8));
}

void x86_video_putc_attr(uint8_t ch, uint8_t attr, uint16_t count)
{
    if (count == 0) count = 1;
    for (unsigned i = 0; i < count && cur_col + i < cur_desc->cols; i++) {
        if (x86_video_is_text())
            *text_cell(cur_row, cur_col + i) = (uint16_t)(ch | (attr << 8));
        else
            gfx_putchar(ch, attr, cur_col + i, cur_row);
    }
}

void x86_video_teletype(uint8_t ch)
{
    unsigned cols = cur_desc->cols;

    switch (ch) {
    case 0x07: break;                                   /* BEL: no glyph */
    case 0x0D: cur_col = 0; break;
    case 0x0A: cur_row++; break;
    case 0x08: if (cur_col) cur_col--; break;
    default:
        if (x86_video_is_text())
            *text_cell(cur_row, cur_col) =
                (uint16_t)(ch | ((*text_cell(cur_row, cur_col) >> 8) << 8));
        else
            gfx_putchar(ch, 0, cur_col, cur_row);
        if (++cur_col >= cols) { cur_col = 0; cur_row++; }
        break;
    }
    if (cur_row >= TEXT_ROWS) {
        x86_video_scroll(1, 0x07);
        cur_row = TEXT_ROWS - 1;
    }
    x86_video_set_cursor(cur_col, cur_row);
}

void x86_video_putpixel(uint16_t x, uint16_t y, uint8_t colour)
{
    if (x >= CGA_WIDTH || y >= CGA_HEIGHT || !cga_storage_ok())
        return;
    uint32_t off = ((y & 1) ? CGA_PLANE_ODD : 0) + (y >> 1) * CGA_ROW_BYTES
                 + (x >> 2);
    unsigned shift = 6 - 2 * (x & 3);
    cga_vram[off] = (uint8_t)((cga_vram[off] & ~(3u << shift))
                              | ((colour & 3u) << shift));
}

/* INT 10h AH=0Bh: BH=0 sets the background/border, BH=1 the palette. Both land
   in the same colour-select register the ports write. */
void x86_video_set_palette_bios(uint8_t which, uint8_t value)
{
    if (which == 0)
        x86_io.cga_color_select = (uint8_t)((x86_io.cga_color_select & 0xF0)
                                            | (value & 0x0F));
    else
        x86_io.cga_color_select = (uint8_t)((x86_io.cga_color_select & ~0x20)
                                            | ((value & 1) ? 0x20 : 0));
    x86_video_refresh_palette();
}

/* ---------------------------------------------------------------------------
 * Text rendering. One glyph row is eight 1-bit pixels; the attribute byte
 * gives foreground in the low nibble and background in the high, both indexing
 * the 16-colour CGA palette. Text mode therefore needs all 16 CLUT entries
 * where mode 4 needs four.
 */

/* The leftmost visible column, honouring the (now vestigial) pan window. */
static unsigned text_left(void)
{
    unsigned left = text_scroll_col;
    if (x86_video_pan >= 0)
        left = (unsigned)x86_video_pan;
    if (left > TEXT_COLS - TEXT_VIS_COLS)
        left = TEXT_COLS - TEXT_VIS_COLS;
    return left;
}

/* Rank the (fg,bg) pairs this frame uses and give the top AA_BLOCKS of them a
 * four-entry CLUT block each. Returns with `aa_base`, `aa_flat`, the CLUT and
 * `aa_letterbox` consistent; sets `cga_clut_dirty` only when the allocation
 * actually moved, because re-pushing the CLUT on a frame the panel is already
 * scanning changes colours under the beam.
 */
#if X86_TEXT_AA
static void text_alloc_palette(void)
{
    /* Static, not automatic. 256 bytes of histogram plus the key array is a
       lot to put on the stack of a function the frame loop calls from inside
       the emulator's own call chain, and overflowing it there does not look
       like a video bug -- it corrupts guest state and surfaces as the CPU
       faulting on a perfectly good instruction. */
    static uint16_t count[128];
    memset(count, 0, sizeof count);
    for (unsigned i = 0; i < TEXT_COLS * TEXT_ROWS; i++) {
        uint16_t cell = ((uint16_t *)cga_vram)[i];
        unsigned fg = (cell >> 8) & 0x0F, bg = (cell >> 12) & 0x07;
        if (fg == bg || aa_glyph_flat[cell & 0xFF])
            continue;                   /* one flat colour: no levels needed */
        count[(bg << 4) | fg]++;
    }

    uint8_t key[AA_BLOCKS];
    unsigned n = 0;
    for (; n < AA_BLOCKS; n++) {
        unsigned best = 0, bestk = 0;
        for (unsigned k = 0; k < 128; k++)
            if (count[k] > best) { best = count[k]; bestk = k; }
        if (!best)
            break;
        key[n] = (uint8_t)bestk;
        count[bestk] = 0;
    }

    if (n == aa_nblocks && !memcmp(key, aa_key, n))
        return;                         /* same pairs as last frame */
    aa_nblocks = n;
    memcpy(aa_key, key, n);

    memset(aa_base, AA_NONE, sizeof aa_base);
    for (unsigned b = 0; b < n; b++) {
        aa_base[key[b]] = (uint8_t)(b * AA_LEVELS);
        uint32_t f = cga_argb[key[b] & 15], g = cga_argb[(key[b] >> 4) & 7];
        for (unsigned l = 0; l < AA_LEVELS; l++) {
            uint32_t v = 0xFF000000u;
            for (unsigned s = 0; s < 24; s += 8) {
                unsigned a = (g >> s) & 0xFF, z = (f >> s) & 0xFF;
                v |= (uint32_t)(a + (int)(z - a) * (int)l / (AA_LEVELS - 1)) << s;
            }
            cga_clut[b * AA_LEVELS + l] = v;
        }
    }
    /* Anything the eight blocks did not cover still has to be drawn, and it is
       drawn bilevel in the nearest colour that IS published -- degrading, not
       corrupting. With every block allocated the entry set is rich enough that
       "nearest" is usually exact. */
    for (unsigned c = 0; c < 16; c++) {
        unsigned bestd = ~0u, besti = 0;
        for (unsigned e = 0; e < n * AA_LEVELS; e++) {
            int dr = (int)((cga_clut[e] >> 16) & 0xFF) - (int)((cga_argb[c] >> 16) & 0xFF);
            int dg = (int)((cga_clut[e] >> 8) & 0xFF) - (int)((cga_argb[c] >> 8) & 0xFF);
            int db = (int)(cga_clut[e] & 0xFF) - (int)(cga_argb[c] & 0xFF);
            unsigned d = (unsigned)(dr * dr + dg * dg + db * db);
            if (d < bestd) { bestd = d; besti = e; }
        }
        aa_flat[c] = (uint8_t)besti;
    }
    /* Unused entries would otherwise keep whatever the previous allocation or
       retro-go's menu left in them, and the firmware darkens all 32. */
    for (unsigned e = n * AA_LEVELS; e < X86_TEXT_CLUT_ENTRIES; e++)
        cga_clut[e] = cga_argb[0];
    aa_letterbox = n ? aa_flat[0] : 0;
    cga_clut_dirty = 1;
}
#endif

/*
 * 40-column text (modes 0 and 1), at the authentic 8x8 cell.
 *
 * 40 x 8 = 320, so this is the one text case that needs no condensed face at
 * all: it draws the SAME 8x8 CP437 table the BIOS hands the guest at F000:F000
 * (x86_font8x8()), which is also what a real CGA character generator shows.
 * Two word stores per glyph row, one per nibble, through the same 16-entry
 * bilevel mask the 4 px path uses -- no second font and no second table.
 */
static void text_render_wide(uint8_t *dst, uint32_t stride)
{
    const unsigned char (*font)[8] = x86_font8x8();

    for (unsigned row = 0; row < TEXT_ROWS; row++) {
        for (unsigned col = 0; col < 40; col++) {
            uint16_t cell = *text_cell(row, col);
            const unsigned char *g = font[cell & 0xFF];
            uint32_t fw = (uint32_t)((cell >> 8) & 0x0F) * 0x01010101u;
            uint32_t bw = (uint32_t)((cell >> 12) & 0x07) * 0x01010101u;
            uint8_t *o = dst + row * CELL_H * stride + col * 8;

            for (unsigned gy = 0; gy < CELL_H; gy++) {
                /* font8x8 puts the LEFTMOST pixel in bit 0 of the row byte
                   (Hepper's tables are little-endian per row), and text_mask4
                   also indexes low-bit-first, so each nibble maps straight
                   across with no reversal. */
                unsigned bits = g[gy];
                uint32_t m0 = text_mask4[bits & 0x0F];
                uint32_t m1 = text_mask4[(bits >> 4) & 0x0F];
                *(uint32_t *)(o + gy * stride)     = (m0 & fw) | (~m0 & bw);
                *(uint32_t *)(o + gy * stride + 4) = (m1 & fw) | (~m1 & bw);
            }
        }
    }
}

/*
 * One glyph row is one 32-bit store in both paths.
 *
 * Bilevel:  out = (mask & fg_word) | (~mask & bg_word), the mask coming from a
 * 16-entry table. Anti-aliased: out = level_word + block_base, the palette
 * doing the colour mixing. Cell origins are `vc * 4` into a 320-byte row, so
 * every one of them is 4-byte aligned and the word stores are safe.
 */
static void text_render(uint8_t *dst, uint32_t stride)
{
    unsigned left = text_left();

    /* THE COLUMN COUNT SELECTS THE FONT, which is the previous port's whole
       two-font scheme and the reason modes 0/1 need nothing else: 40 columns of
       an 8 px cell and 80 columns of a 4 px cell are both exactly 320 px. */
    if (cur_desc->cols == 40) {
        text_render_wide(dst, stride);
        return;
    }

    for (unsigned row = 0; row < TEXT_ROWS; row++) {
        for (unsigned vc = 0; vc < TEXT_VIS_COLS; vc++) {
            unsigned col = left + vc;
            uint16_t cell = (col < TEXT_COLS) ? *text_cell(row, col) : 0x0720;
            /* CP437, so the WHOLE byte indexes the font. Masking to 7 bits
               turned every box-drawing rule, shade and block of a full-screen
               DOS UI into an unrelated letter -- correct-looking text next to
               interleaved gibberish, which reads like a stride bug and is not
               one. */
            unsigned ch = cell & 0xFF;
            uint8_t fg = (uint8_t)((cell >> 8) & 0x0F);
            uint8_t bg = (uint8_t)((cell >> 12) & 0x07);
            uint8_t *o = dst + row * CELL_H * stride + vc * CELL_W;

#if X86_TEXT_AA
            unsigned base = x86_text_aa ? aa_base[(bg << 4) | fg] : AA_NONE;
            const unsigned char *g = font4x8aa_cp437[ch];
            (void)g;
            if (base != AA_NONE) {
                uint32_t add = base * 0x01010101u;
                for (unsigned gy = 0; gy < CELL_H; gy++)
                    *(uint32_t *)(o + gy * stride) = text_level4[g[gy]] + add;
                continue;
            }
            /* No block for this pair: bilevel, in the nearest colours that
               ARE published. */
            uint32_t fw = (x86_text_aa ? aa_flat[fg] : fg) * 0x01010101u;
            uint32_t bw = (x86_text_aa ? aa_flat[bg] : bg) * 0x01010101u;
#else
            uint32_t fw = fg * 0x01010101u, bw = bg * 0x01010101u;
#endif
            for (unsigned gy = 0; gy < CELL_H; gy++) {
#if X86_TEXT_BILEVEL_FONT
                unsigned bits = font4x8_cp437[ch][gy] & 0x0F;
#else
                /* No bilevel table linked: threshold the 2-bit glyph at half. */
                unsigned v = g[gy], bits = 0;
                for (unsigned i = 0; i < 4; i++)
                    if (((v >> (2 * i)) & 3) >= 2)
                        bits |= 1u << i;
#endif
                uint32_t m = text_mask4[bits];
                *(uint32_t *)(o + gy * stride) = (m & fw) | (~m & bw);
            }
        }
    }
}

