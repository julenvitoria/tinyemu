/*
 * One frame. `dst` is the LUT8 framebuffer, `stride` its pitch in bytes.
 * 320x200 lands inside a 320x240 panel, so the picture is centred with 20
 * blank rows above and below rather than stretched -- CGA pixels are not
 * square, but scaling costs a multiply per pixel and looks worse.
 */
/* The renderer proper. x86_video_render() below is the cycle bracket around
   it; see x86_vprof.h. In Mode Y this call IS the de-interleave blit -- 64,000
   bytes into a framebuffer the firmware's MPU maps strongly-ordered and
   NON-BUFFERABLE -- which is exactly why it is worth timing apart from the
   rest of the paint. */
static void video_render_body(uint8_t *dst, uint32_t stride)
{
    /* Clear the letterbox. 320x200 into a 240-row panel leaves 20 rows top
       and bottom; leaving them alone means they keep whatever the firmware or
       the other buffer had, reinterpreted through the CGA palette -- which is
       what turns an otherwise black screen into colour flashes. */
    /* The donation policy runs HERE and nowhere else: once per frame, before
       anything has read the card, and before a mode set can adopt a new one.
       See x86_video_policy_tick(). */
    x86_video_policy_tick();
    /* Follow the guest BEFORE anything reads the mode: the renderer, the
       palette and the letterbox clear must all be for the same frame. */
    mode_sync_from_bda();

    unsigned band = (240u - CGA_HEIGHT) / 2u;
    int aa = X86_TEXT_AA && x86_video_is_text() && x86_text_aa;
    /* Index 0 is CGA black everywhere EXCEPT under a per-frame anti-aliased
       allocation, where entry 0 is level 0 of whichever pair happened to rank
       first. Clearing with a hardcoded 0 there paints the letterbox in that
       pair's background, which reads as a coloured border nobody asked for. */
    /* Leaving the anti-aliased allocation behind when the renderer switches
       back is not a cosmetic slip: entry 1 is then a grey ramp step rather
       than blue, so every bilevel cell draws in a colour from the pair that
       happened to rank first last frame. */
    uint8_t clear = 0;
#if X86_TEXT_AA
    if (aa != aa_was_on) {
        aa_was_on = aa;
        if (!aa)
            x86_video_refresh_palette();
        else
            aa_nblocks = 0;
    }
    if (aa) {
        text_alloc_palette();
        clear = aa_letterbox;
    }
#endif
    memset(dst, clear, band * stride);
    memset(dst + (band + CGA_HEIGHT) * stride, clear, band * stride);

    uint8_t *top = dst + band * stride;
    /* One entry per CHANGE of renderer, not per frame: the ring is 16 deep and
       a per-frame entry would flush the causes off the end in a quarter of a
       second. */
    {
        static int last_text = -1;
        int now = x86_video_is_text() ? 1 : 0;
        if (now != last_text) {
            last_text = now;
            x86_video_log_event(3, (uint32_t)now, x86_video_mode_byte);
        }
    }
    switch (cur_desc->kind) {
    case VM_TEXT:
        text_render(top, stride);
        break;
    case VM_CGA1:
        cga_mode6_blit(top, stride);
        break;
    case VM_VGA8:
        vga13_blit(top, stride);
        break;
    case VM_EGA4:
        blit_ega16(top, stride);
        break;
    default:
        cga_mode4_blit(top, cga_vram, cga_vram + CGA_PLANE_ODD,
                       cga_expand, stride - CGA_WIDTH);
        break;
    }
}

/*
 * Mode 6: 640x200 at 1 bpp, in the same two-bank interleave as mode 4 and the
 * same 80 bytes per row -- one byte is EIGHT pixels here, so a row is 640 wide
 * and is decimated to the panel's 320 by the OR rule in cga1_expand.
 *
 * In C rather than in cga_blit.S deliberately: it is 80 iterations of two table
 * lookups over a mode almost nothing uses, against an assembly routine that
 * would have to be maintained alongside the hot one.
 */
static void cga_mode6_blit(uint8_t *dst, uint32_t stride)
{
    for (unsigned y = 0; y < CGA_HEIGHT; y++) {
        const uint8_t *src = cga_vram + ((y & 1) ? CGA_PLANE_ODD : 0)
                           + (y >> 1) * CGA_ROW_BYTES;
        uint32_t *out = (uint32_t *)(dst + y * stride);
        for (unsigned x = 0; x < CGA_ROW_BYTES; x++) {
            uint8_t b = src[x];
            /* Leftmost source pixel is bit 7, and the leftmost output pixel
               must land in the LOW byte of the word. */
            out[x] = cga1_expand[b >> 4] | (cga1_expand[b & 0x0F] << 16);
        }
    }
}

/* ===========================================================================
 * VGA mode 13h -- 320x200x256 linear at 0xA0000.
 *
 * This is the cheapest 256-colour mode there is, and the reason is that its
 * aperture is byte-for-byte the format of our LUT8 framebuffer: one byte per
 * pixel, row y at y*320, 64,000 bytes, no banks, no interleave, no planes.
 * The blit is 200 memcpys and NOTHING is added to the store path -- which is
 * the whole reason this mode is buildable here and EGA/Mode X is not. A planar
 * mode puts a latch/mask/write-mode register file between the CPU and video
 * memory, so every guest STORE runs through emulated adapter logic, and our
 * VRAM is deliberately plain mapped RAM with no MMIO path at all.
 *
 * Two pieces of state come from the caller rather than from .bss: the 64 KB
 * aperture and this 2 KB palette block. RAM_EMU headroom is a few KB and
 * overshooting it is SILENT (STATUS: "running out is QUIET"), so 66 KB of new
 * static data would not merely be tight, it would break the guest allocation
 * with no message. Both live in the LCD bonus pool, which is cached AXI.
 */
/* (vga_aperture / vga_dac / vga_clut256 are declared up with cga_vram: the
   memory mapping needs the aperture pointer long before this section.) */

/* DAC port state. 0x3C8 sets the WRITE index, 0x3C7 the READ index; 0x3C9 is
 * a STREAM against a counter that advances after every third byte.
 *
 * The stream is the whole reason this cannot live in a port latch the way
 * 0x3D8/0x3D9 do. A game writes the index once and then 768 consecutive bytes,
 * so under a "last value written is the state" model 767 of them are lost and
 * the screen comes out one colour.
 */
static uint16_t vga_dac_wr;         /* byte offset into vga_dac, write side  */
static uint16_t vga_dac_rd;         /* byte offset into vga_dac, read side   */
static uint8_t  vga_dac_mask = 0xFF;    /* 0x3C6 PEL mask: latched, applied
                                           nowhere -- a guest reads it back  */
static uint8_t  vga_dac_dirty;      /* rebuild vga_clut256 before the push   */

/* Host-visible: mode 13h with no aperture is refused, and this says so. */
volatile uint32_t x86_vga13_ok;
volatile uint32_t x86_vga_dac_writes;   /* DAC bytes the guest has streamed  */

void x86_video_set_aperture(void *aperture, void *palette_block)
{
    vga_aperture = (uint8_t *)aperture;
    /* The store hook resolves its window offsets against the same base. One
       assignment, one owner -- the hook must never learn the aperture from a
       second source. */
    x86_vga_planar_aperture = vga_aperture;
    vga_dac      = (uint8_t *)palette_block;
    vga_clut256  = palette_block
                 ? (uint32_t *)((uint8_t *)palette_block + 768) : 0;
    x86_vga13_ok = (vga_aperture && vga_dac) ? 1 : 0;
    if (!x86_vga13_ok)
        return;
    memset(vga_aperture, 0, X86_VGA_APERTURE_BYTES);
    /* Power-on DAC: the standard VGA 256-colour default is 16 CGA colours,
       16 greys and a 6x6x6-ish cube. We plant the 16 CGA colours (so a guest
       that sets 13h and draws without touching the DAC gets recognisable
       colours rather than black) and a linear grey ramp over the rest. That
       is a DEFAULT, not a claim to match IBM's table -- every mode-13h title
       loads its own palette, and a guest that does not is out of spec. */
    for (unsigned i = 0; i < 256; i++) {
        unsigned r, g, b;
        if (i < 16) {
            uint32_t c = cga_argb[i];
            r = ((c >> 16) & 0xFF) >> 2;
            g = ((c >>  8) & 0xFF) >> 2;
            b = ( c        & 0xFF) >> 2;
        } else {
            r = g = b = ((i - 16) * 63u) / 239u;
        }
        vga_dac[i * 3 + 0] = (uint8_t)r;
        vga_dac[i * 3 + 1] = (uint8_t)g;
        vga_dac[i * 3 + 2] = (uint8_t)b;
    }
    vga_dac_wr = vga_dac_rd = 0;
    vga_dac_dirty = 1;
}

/*
 * DAC 6 bits -> 8. `(v << 2) | (v >> 4)` and not a plain `<< 2`: 63 must map
 * to 255, not to 252, or every white is 1.2% grey and every fade-to-white
 * stops short of it.
 */
static inline uint32_t dac_expand(unsigned r, unsigned g, unsigned b)
{
    return (uint32_t)(((r << 2 | r >> 4) & 0xFF) << 16)
         | (uint32_t)(((g << 2 | g >> 4) & 0xFF) <<  8)
         | (uint32_t)( ((b << 2 | b >> 4) & 0xFF)      );
}

static void vga_clut_rebuild(void)
{
    if (!vga_dac_dirty || !vga_clut256)
        return;
    for (unsigned i = 0; i < 256; i++)
        vga_clut256[i] = dac_expand(vga_dac[i * 3 + 0],
                                    vga_dac[i * 3 + 1],
                                    vga_dac[i * 3 + 2]);
    vga_dac_dirty = 0;
}

/*
 * The 256-entry CLUT, or NULL if a 256-colour mode is not up.
 *
 * The frame loop uses non-NULL to choose lcd_set_clut_ext() over the ordinary
 * 32-entry lcd_set_clut(). They are different firmware paths, not a count
 * argument: lcd_set_clut() stores a 40%-darkened TWIN of entry i at count+i so
 * retro-go's overlay can dim the screen by OR-ing LCD_DARKEN_BIT (0x20), and
 * 256 entries would need 512 hardware slots against the LTDC's 256. A
 * 256-colour mode therefore has to own the whole table, and the accepted price
 * is that the darken stops working while it does -- see the caveat in
 * docs/03 and in gw_lcd.h.
 */
const uint32_t *x86_video_clut256(void)
{
    if (cur_desc->kind != VM_VGA8 || !vga_clut256)
        return 0;
    vga_clut_rebuild();
    return vga_clut256;
}

/* --- DAC ports, called from x86_io.c ------------------------------------- */

void x86_vga_dac_set_write_index(uint8_t idx) { vga_dac_wr = (uint16_t)idx * 3u; }
void x86_vga_dac_set_read_index(uint8_t idx)  { vga_dac_rd = (uint16_t)idx * 3u; }
void x86_vga_dac_set_mask(uint8_t m)          { vga_dac_mask = m; }
uint8_t x86_vga_dac_get_mask(void)            { return vga_dac_mask; }

void x86_vga_dac_write(uint8_t v)
{
    if (!vga_dac)
        return;
    /* Stored AS THE GUEST WROTE IT, 6 bits per channel, because read-modify-
       write fade loops read the DAC back and must get their own value. The
       scaling to 8 bits happens in the consumer. */
    vga_dac[vga_dac_wr] = (uint8_t)(v & 0x3F);
    if (++vga_dac_wr >= 768u)
        vga_dac_wr = 0;
    vga_dac_dirty = 1;
    x86_vga_dac_writes++;
    /* A palette change is a CLUT reprogram, not a repaint: the pixels in the
       aperture do not move, so the frame loop only has to re-push. */
    if (cur_desc->kind == VM_VGA8)
        cga_clut_dirty = 1;
}

uint8_t x86_vga_dac_read(void)
{
    uint8_t v;
    if (!vga_dac)
        return 0x3F;
    v = vga_dac[vga_dac_rd];
    if (++vga_dac_rd >= 768u)
        vga_dac_rd = 0;
    return v;
}

/*
 * Set a block of DAC entries at once -- INT 10h AH=10h AL=12h. Routed here
 * rather than reimplemented in the BIOS so there is ONE palette model and not
 * two that can disagree.
 */
void x86_vga_dac_set_block(unsigned first, unsigned count, const uint8_t *rgb)
{
    if (!vga_dac || first >= 256u)
        return;
    if (count > 256u - first)
        count = 256u - first;
    for (unsigned i = 0; i < count * 3u; i++)
        vga_dac[first * 3u + i] = (uint8_t)(rgb[i] & 0x3F);
    vga_dac_dirty = 1;
    x86_vga_dac_writes += count * 3u;
    if (cur_desc->kind == VM_VGA8)
        cga_clut_dirty = 1;
}

/*
 * The blit. 200 rows of 320 bytes out of the aperture into the letterboxed
 * framebuffer -- an identity copy, because the guest's format IS the panel's.
 *
 * A row loop and not one 64,000-byte memcpy: the framebuffer stride is 320
 * here so the two happen to be equal, but the stride is the caller's and a
 * single copy would silently break the moment it is not.
 */
/*
 * NEGATIVE CONTROLS for the Mode Y blit. Each is REQUIRED to fail the Mode Y
 * arm of tests/test_video.py; see the header there for the whole set.
 *
 * NOT AMONG THEM: "read the unchained aperture linearly". That was the obvious
 * first choice and the reference measured it SURVIVING, because at a display
 * start of 0 and an Offset of 40 the correct de-interleave IS the linear read
 * (the identity in the module header). A mutation that is a no-op at the
 * geometry under test cannot be the control -- 15-mode-y.md records it so it is
 * not proposed again.
 */
#ifndef X86_MODEY_STRIDE_NEGCTL
#define X86_MODEY_STRIDE_NEGCTL 0   /* blit at 40 plane offsets/row, not 80  */
#endif
#ifndef X86_MODEY_BLIT_NEGCTL
#define X86_MODEY_BLIT_NEGCTL 0     /* decode four FLAT planes, not interleaved */
#endif

/* 320 pixels is 80 plane offsets, and one plane offset is four interleaved
   bytes, so a displayed row is 80 plane offsets wide however far apart rows
   are. */
#define VGA13_ROW_OFFSETS  (X86_VGA13_WIDTH / 4u)

static void vga13_blit(uint8_t *dst, uint32_t stride)
{
    const uint8_t *src = vga_aperture;
    if (!src) {                       /* refused at mode-select; belt and braces */
        for (unsigned y = 0; y < X86_VGA13_HEIGHT; y++)
            memset(dst + y * stride, 0, X86_VGA13_WIDTH);
        return;
    }
    if (!x86_vga_is_unchained()) {
        /* CHAINED 13h, BYTE FOR BYTE WHAT IT ALWAYS WAS. The unchained work
           below must not cost this path a single instruction: it is the mode
           most titles use and the reason 13h was buildable here at all. */
        /* One contiguous 64,000-byte run, so a 2-D engine can take it whole --
           but ONLY at the panel stride, where dst rows abut. See the hook. */
        if (x86_video_blit_hook && stride == X86_VGA13_WIDTH
            && x86_video_blit_hook(dst, src,
                                   X86_VGA13_WIDTH * X86_VGA13_HEIGHT) == 0)
            return;
        for (unsigned y = 0; y < X86_VGA13_HEIGHT; y++)
            memcpy(dst + y * stride, src + y * X86_VGA13_WIDTH, X86_VGA13_WIDTH);
        return;
    }

    /*
     * UNCHAINED ("Mode Y"). The de-interleave is the identity at the standard
     * geometry -- 4*(y*80 + (x>>2)) + (x&3) == 320*y + x -- so all this loop
     * adds over the chained one is a per-row SOURCE OFFSET, which is what makes
     * a non-zero CRTC display start and a non-standard Offset render correctly.
     * At start 0 and Offset 40 it reduces to the loop above exactly.
     */
    const unsigned pitch = X86_MODEY_STRIDE_NEGCTL ? x86_vga_row_pitch() / 2u
                                                   : x86_vga_row_pitch();
    const unsigned start = x86_vga_crtc_start();

    for (unsigned y = 0; y < X86_VGA13_HEIGHT; y++, dst += stride) {
        /* The CORE owns the page fold, and it is NOT a mask -- the page stride
           is whatever the guest programmed, and WOLF3D's is 16,640. This is the
           same lookup the store path uses, so the blit and the writes cannot
           disagree about where a row is. */
        /* POINTER, not an aperture offset. Pages 1 and 2 have storage of their
           own now when the donation was funded, and they are not in the
           aperture -- x86_vga_modey_row() can only answer for page 0. */
        const uint8_t *pb;
        uint32_t a;

        if (!x86_vga_modey_row_at(start + y * pitch, &pb, &a)) {
            /* No aperture storage for this row: off-screen, or a page tail.
               BLACK rather than whatever the previous frame left, so a
               mis-learned layout is VISIBLE instead of merely plausible. */
            memset(dst, 0, X86_VGA13_WIDTH);
            continue;
        }
#if X86_MODEY_BLIT_NEGCTL
        /* Four FLAT planes instead of four interleaved ones. */
        for (unsigned x = 0; x < X86_VGA13_WIDTH; x++)
            dst[x] = pb[(x & 3u) * X86_MODEY_PLANE_OFFSETS + a + (x >> 2)];
#else
        /* A row is contiguous in the interleaved store unless it runs off the
           end of the aliased page, which only a non-zero start can do. Split
           rather than read past the aperture. */
        if (a + VGA13_ROW_OFFSETS <= X86_MODEY_PLANE_OFFSETS) {
            memcpy(dst, pb + 4u * a, X86_VGA13_WIDTH);
        } else {
            const unsigned head = (X86_MODEY_PLANE_OFFSETS - a) * 4u;
            memcpy(dst, pb + 4u * a, head);
            memcpy(dst + head, pb, X86_VGA13_WIDTH - head);
        }
#endif
    }
}

/* ===========================================================================
 * EGA mode 0Dh -- 320x200, 16 colours, four bitplanes at 0xA0000.
 *
 * The planes are NOT the aperture. While 0Dh is armed the adapter partitions
 * things so that the bottom 16 KB of the aperture is the CPU-visible READ
 * SHADOW -- which is what guest 0xA0000 folds onto, so reads cost nothing --
 * and the planes are a separate interleaved block out of the arena.
 * x86_vga_ega_planes() is the only correct source here.
 *
 * "Interleaved" means plane p at offset a lives at planes[4*a + p], so all four
 * planes of one 8-pixel group are a single aligned 32-bit load. That layout is
 * tiny386's / QEMU's; the idea is theirs.
 *
 * KEEN 4'S LEVEL BACKGROUNDS ARE STILL NOT FULLY REACHABLE HERE, AND THAT IS
 * ARITHMETIC. The Galaxy engine caches its tile art in off-screen video memory
 * and blits it out with latch copies; measured on the reference, 97.2% of those
 * copies source from beyond an 8 KB plane and its write high-water is plane
 * offset 65,536 -- a 256 KB card. The card is sized from the arena now (see
 * planar_storage_follow), which reaches 19,456 offsets on the shipping layout
 * instead of 8,192: the whole 200-row frame is addressable at Keen's 64-byte
 * pitch where it used to cut off at row 128, and the off-screen tiles that do
 * not fit still draw as nothing. A complete frame with wrong tiles, not a
 * pixel-correct one.
 *
 * KNOWN LIMIT OF THE LOAN: while 0Dh is up the guest's 0xB8000 mapping still
 * points at the pages the planes now hold. Our own writers stand down
 * (cga_storage_ok()); a guest that writes text memory it cannot see while in a
 * graphics mode corrupts plane bytes instead. Nothing needs 32 KB to park it
 * on, and no title has been seen to do it.
 */
#define EGA_WIDTH     320u
#define EGA_ROWS      200u
#define EGA_ROWBYTES  (EGA_WIDTH / 8u)   /* 40 bytes per plane per row */

/* (ega_attr_shadow / ega_dac_shadow / ega_clut_valid are declared up with the
   other mode statics: x86_video_refresh_palette() invalidates the flag, and it
   runs long before this section.) */

/*
 * Pixel value -> Attribute Controller palette register -> DAC entry -> RGB.
 * BOTH indirections are real and a game can repaint by writing either.
 *
 * DECLARE EXACTLY 32 ENTRIES, NEVER 16. lcd_set_clut(clut, count) stores a
 * darkened twin of entry i at count+i, while retro-go's overlay dims a pixel by
 * ORing LCD_DARKEN_BIT, which is a fixed +32. The two agree only at count == 32,
 * so a 16-entry push would leave the menu dimming reading colours 16..31 --
 * which is why 16-31 are MIRRORED here rather than left stale: unreachable from
 * a 4-bit pixel, but lcd_pack_color() searches the whole table.
 */
static void ega_sync_palette(void)
{
    const uint8_t *attr = x86_vga_attr_palette();

    if (!cga_clut || !vga_dac)
        return;
    if (ega_clut_valid
        && memcmp(ega_attr_shadow, attr, sizeof ega_attr_shadow) == 0
        && memcmp(ega_dac_shadow, vga_dac, sizeof ega_dac_shadow) == 0)
        return;

    memcpy(ega_attr_shadow, attr, sizeof ega_attr_shadow);
    memcpy(ega_dac_shadow, vga_dac, sizeof ega_dac_shadow);

    for (unsigned i = 0; i < 16; i++) {
        const uint8_t *e = vga_dac + (attr[i] & 0x3Fu) * 3u;
        cga_clut[i] = dac_expand(e[0], e[1], e[2]);
    }
    for (unsigned i = 16; i < X86_TEXT_CLUT_ENTRIES; i++)
        cga_clut[i] = cga_clut[i - 16];

    ega_clut_valid = 1;
    cga_clut_dirty = 1;
}

static void blit_ega16(uint8_t *dst, uint32_t stride)
{
    const uint8_t *planes = x86_vga_ega_planes();
    const uint32_t vram   = x86_vga_ega_plane_offsets();
    /* The display is a WINDOW onto plane memory, not the bottom of it. A game
       that scrolls moves the CRTC start address and widens the row pitch; both
       have to be honoured or the picture is a sheared crop. */
    const unsigned pitch = x86_vga_row_pitch();
    const unsigned pan   = x86_vga_pel_panning();
    unsigned addr = x86_vga_crtc_start();

    ega_sync_palette();
    if (!planes) {
        for (unsigned y = 0; y < EGA_ROWS; y++)
            memset(dst + y * stride, 0, EGA_WIDTH);
        return;
    }

    /* One extra group per row so the pel-panning shift has 8 more pixels to
       pull from. */
    for (unsigned y = 0; y < EGA_ROWS; y++, dst += stride, addr += pitch) {
        uint8_t line[EGA_WIDTH + 8];
        unsigned a = addr;
        uint8_t *out = line;

        for (unsigned g = 0; g < EGA_ROWBYTES + 1u; g++, a++) {
            uint32_t p0, p1, p2, p3;

            if (a < vram) {
                /* One 32-bit load, four planes. Bit 7 is the leftmost pixel. */
                uint32_t q;
                memcpy(&q, planes + 4u * a, 4);
                p0 = q & 0xFFu;         p1 = (q >> 8) & 0xFFu;
                p2 = (q >> 16) & 0xFFu; p3 = (q >> 24) & 0xFFu;
            } else {
                /* Past the memory this card has fitted: reads as ZERO, exactly
                   as the store path discards writes there. The card-size
                   boundary is then visible in the picture rather than being an
                   internal detail. */
                p0 = p1 = p2 = p3 = 0;
            }
            for (int bit = 7; bit >= 0; bit--)
                *out++ = (uint8_t)(((p0 >> bit) & 1u)
                                 | (((p1 >> bit) & 1u) << 1)
                                 | (((p2 >> bit) & 1u) << 2)
                                 | (((p3 >> bit) & 1u) << 3));
        }
        memcpy(dst, line + pan, EGA_WIDTH);
    }
}

/* ---------------------------------------------------------------------------
 * Mode and cursor state.
 */
/* Not static: the harness reads it to know which renderer to check against.
   `x86_video_mode()` is the call for C callers; this is the storage. */

/*
 * Every event that can change what the renderer draws, in order.
 *
 * "The mode did not switch" and "the mode switched and the renderer did not
 * follow" are the same picture -- a screen of pixels -- and a sampled
 * `x86_video_mode_byte` cannot separate them: a mode set that is immediately
 * overwritten, or one that never happens, both read as a constant. The ring
 * records the CAUSE, so the order of a BIOS set against a 0x3D8 write is
 * visible.
 *
 * Word layout: (tag << 24) | (aux << 8) | value
 *   tag 1  mode adopted (INT 10h, or the BDA)   value = mode, aux = columns
 *   tag 2  port 0x3D8 write                     value = the byte written
 *   tag 3  renderer follow                      value = mode, aux = is_text
 *   tag 5  mode REFUSED, previous one stays     value = old mode, aux = asked
 *   tag 6  INT 10h AH=00 set-mode REQUESTED     value = old mode, aux = asked
 *   tag 7  a display CLAIM was refused          value = 0 CGA loan, 1 EGA card
 *   tag 8  EGA card fitted                      aux = plane offsets >> 8
 *          (logged before the decision -- a set to the mode already up clears
 *           the display and adopts nothing, so it has no tag 1 of its own)
 *
 * A run with tag 1 and tag 3 disagreeing is a renderer that did not follow the
 * guest; a run of tag 5 names a mode a title wants and we do not have, which is
 * otherwise indistinguishable from a guest that draws nothing.
 * scripts/probe.py --dump x86_video_mode_log:16x4
 */
volatile uint32_t x86_video_mode_log[16];
volatile uint32_t x86_video_mode_log_idx = 0;

void x86_video_log_event(uint32_t tag, uint32_t aux, uint32_t value)
{
    x86_video_mode_log[x86_video_mode_log_idx & 15] =
        (tag << 24) | ((aux & 0xFFFFu) << 8) | (value & 0xFFu);
    x86_video_mode_log_idx++;
}
